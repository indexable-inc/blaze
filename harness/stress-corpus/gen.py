#!/usr/bin/env python3
"""Writes the generated sources of the stress corpus (harness/stress-corpus/README.md).

usage: gen.py '{"mode": "write"}'   rewrite every generated file
       gen.py '{"mode": "check"}'   exit 1 naming each generated file that is stale or missing
       gen.py -                     read the JSON value from stdin
       gen.py path/to/input.json    read it from a file

The input is one JSON object parsed into `Input`; unknown fields are refused. The output is a
pure function of this file: no randomness, no clock, no hash-map order, so `check` holds the
checked-in files to it byte for byte. Each crate's `fn main` asserts values this script computes,
so a build that compiles but behaves wrong fails when run.
"""

from __future__ import annotations

import dataclasses
import json
import sys
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = "// @generated by harness/stress-corpus/gen.py; edit the generator, not this file.\n"
U32 = 0xFFFF_FFFF


@dataclass(frozen=True)
class Input:
    mode: str

    def __post_init__(self) -> None:
        if self.mode not in ("write", "check"):
            raise SystemExit(f"gen.py: mode {self.mode!r} is not one of 'write', 'check'")


def parse_input(argv: list[str]) -> Input:
    if len(argv) != 2:
        raise SystemExit(__doc__)
    arg = argv[1]
    if arg == "-":
        text = sys.stdin.read()
    elif arg.lstrip().startswith("{"):
        text = arg
    else:
        text = Path(arg).read_text()
    value = json.loads(text)
    if not isinstance(value, dict):
        raise SystemExit(f"gen.py: input must be a JSON object, got {type(value).__name__}")
    known = {f.name for f in dataclasses.fields(Input)}
    unknown = sorted(set(value) - known)
    if unknown:
        raise SystemExit(f"gen.py: unknown input fields {unknown}; known: {sorted(known)}")
    missing = sorted(known - set(value))
    if missing:
        raise SystemExit(f"gen.py: missing input fields {missing}")
    return Input(**value)


# --- deep-vector: one `vec![...]` of untyped integer literals (rustc-perf's deep-vector) ---

DEEP_VECTOR_LEN = 135_000


def deep_vector() -> dict[str, str]:
    values = [(i * 31 + i // 7) % 10 for i in range(DEEP_VECTOR_LEN)]
    rows = []
    for at in range(0, len(values), 32):
        rows.append("        " + ", ".join(str(v) for v in values[at : at + 32]) + ",")
    body = "\n".join(rows)
    main = (
        HEADER
        + "//! rustc-perf's deep-vector: one `vec!` literal of untyped integers, each needing\n"
        + "//! inference and integer fallback, then a checked sum.\n\n"
        + "fn main() {\n"
        + "    let v = vec![\n"
        + body
        + "\n    ];\n"
        + "    let total: i64 = v.iter().map(|&x| x as i64).sum();\n"
        + f"    assert_eq!(v.len(), {DEEP_VECTOR_LEN});\n"
        + f"    assert_eq!(total, {sum(values)});\n"
        + '    println!("deep-vector ok: {} elements, sum {}", v.len(), total);\n'
        + "}\n"
    )
    return {"deep-vector/src/main.rs": main}


# --- trivial-consts: thousands of libc-style `const NAME: T = <literal>;` items ---

CONST_COUNT = 6_000
STR_COUNT = 400

# (rust type alias, how the literal is written, how the value is bounded)
CONST_KINDS = [
    ("c_int", "dec", lambda v: v),
    ("c_uint", "hex", lambda v: v),
    ("c_long", "neg", lambda v: -v),
    ("c_ulong", "suffix_u64", lambda v: v * 4_096),
    ("c_short", "dec", lambda v: v % 32_768),
    ("c_ushort", "oct", lambda v: v % 65_536),
    ("c_char", "dec", lambda v: v % 128),
    ("c_uchar", "bin", lambda v: v % 256),
    ("size_t", "underscored", lambda v: v),
    ("ssize_t", "neg", lambda v: -(v % 100_000)),
]


def literal(style: str, v: int) -> str:
    match style:
        case "dec":
            return str(v)
        case "hex":
            return f"0x{v:x}"
        case "neg":
            return str(v)
        case "suffix_u64":
            return f"{v}_u64"
        case "oct":
            return f"0o{v:o}"
        case "bin":
            return f"0b{v:b}"
        case "underscored":
            return f"{v:_}"
    raise AssertionError(style)


def trivial_consts() -> dict[str, str]:
    out = [
        HEADER,
        "//! libc-style constants: thousands of trivial `const` items over C type aliases, a\n",
        "//! table that reads every one, and a few constants that need real const evaluation.\n",
        "#![allow(non_camel_case_types, dead_code)]\n\n",
        "pub type c_int = i32;\npub type c_uint = u32;\npub type c_long = i64;\npub type c_ulong = u64;\n",
        "pub type c_short = i16;\npub type c_ushort = u16;\npub type c_char = i8;\npub type c_uchar = u8;\n",
        "pub type size_t = usize;\npub type ssize_t = isize;\n\n",
    ]
    names: list[str] = []
    total = 0
    for i in range(CONST_COUNT):
        ty, style, bound = CONST_KINDS[i % len(CONST_KINDS)]
        raw = (i * 2_654_435_761) % 1_000_003
        value = bound(raw)
        name = f"K{i:05}_{ty.upper()}"
        names.append(name)
        total += value
        out.append(f"pub const {name}: {ty} = {literal(style, value)};\n")
    out.append("\n")
    for i in range(STR_COUNT):
        out.append(f'pub const NAME_{i:04}: &str = "name_{i:04}";\n')
    out.append("\n")
    for i in range(26):
        out.append(f"pub const LETTER_{i:02}: char = '{chr(ord('a') + i)}';\n")
        out.append(f"pub const FLAG_{i:02}: bool = {'true' if i % 3 == 0 else 'false'};\n")
    out.append("\n/// Every numeric constant above, read once, so each is evaluated and used.\n")
    out.append(f"pub static TABLE: [i64; {CONST_COUNT}] = [\n")
    for at in range(0, len(names), 8):
        out.append("    " + " ".join(f"{n} as i64," for n in names[at : at + 8]) + "\n")
    out.append("];\n")
    out.append(f"\npub const TABLE_SUM: i64 = {total};\n")
    out.append(f'\npub const NAME_LAST: &str = "name_{STR_COUNT - 1:04}";\n')
    return {"trivial-consts/src/consts.rs": "".join(out)}


# --- deep-macro: deep macro_rules recursion and a large token stream ---

CHAIN_LEN = 1_500
REVERSE_LEN = 800
PAIR_COUNT = 12_000


def deep_macro() -> dict[str, str]:
    out = [
        HEADER,
        "//! Invocations of the macros in main.rs: a depth-",
        f"{CHAIN_LEN} item-emitting recursion, a quadratic\n",
        f"//! tt-muncher over {REVERSE_LEN} tokens and one flat invocation of {PAIR_COUNT} pairs.\n\n",
        "fn start() -> u64 {\n    0\n}\n\n",
        "chain! { start;\n",
    ]
    idents = [f"c{i:05}" for i in range(1, CHAIN_LEN + 1)]
    for at in range(0, len(idents), 12):
        out.append("    " + " ".join(idents[at : at + 12]) + "\n")
    out.append("}\n\n")
    out.append(f"pub fn last() -> u64 {{\n    {idents[-1]}()\n}}\n\n")
    numbers = [str(i) for i in range(1, REVERSE_LEN + 1)]
    out.append(f"pub const REV: [u32; {REVERSE_LEN}] = reverse!([\n")
    for at in range(0, len(numbers), 20):
        out.append("    " + " ".join(numbers[at : at + 20]) + "\n")
    out.append("]);\n\n")
    out.append("pairs! {\n")
    pair_sum = 0
    for i in range(PAIR_COUNT):
        a, b = i % 997, (i * 7) % 1_009
        pair_sum += a * b
        out.append(f"    {a} => {b},\n")
    out.append("}\n\n")
    out.append(f"pub const CHAIN_LEN: u64 = {CHAIN_LEN};\n")
    out.append(f"pub const REVERSE_LEN: u32 = {REVERSE_LEN};\n")
    out.append(f"pub const PAIR_COUNT: usize = {PAIR_COUNT};\n")
    out.append(f"pub const PAIR_SUM: u64 = {pair_sum};\n")
    return {"deep-macro/src/generated.rs": "".join(out)}


# --- big-file: one large file of many small items (span and hashing load) ---

BIG_FILE_ITEMS = 6_000


def big_file() -> dict[str, str]:
    lines = [
        HEADER.rstrip("\n"),
        "//! Many small items in one file. The edit in ../edits.json inserts a line above TOP;",
        "//! every span below it shifts by one line and main's line-distance check must still hold.",
        "#![allow(dead_code)]",
        "",
        "pub const TOP: u32 = line!();",
        "",
    ]
    acc = 1
    for i in range(BIG_FILE_ITEMS):
        k = 2 * i + 1
        lines += [
            f"/// Item {i}.",
            f"pub struct S{i:05} {{",
            "    pub a: u32,",
            "}",
            "",
            f"impl S{i:05} {{",
            "    pub fn get(&self) -> u32 {",
            f"        self.a ^ {i}",
            "    }",
            "}",
            "",
            f"pub fn f{i:05}(x: u32) -> u32 {{",
            f"    S{i:05} {{ a: x.wrapping_mul({k}).wrapping_add({i}) }}.get()",
            "}",
            "",
        ]
        acc = (((acc * k) + i) & U32) ^ i
    lines.append(f"pub static FNS: [fn(u32) -> u32; {BIG_FILE_ITEMS}] = [")
    fns = [f"f{i:05}" for i in range(BIG_FILE_ITEMS)]
    for at in range(0, len(fns), 10):
        lines.append("    " + " ".join(f"{f}," for f in fns[at : at + 10]))
    lines.append("];")
    lines.append("")
    lines.append(f"pub const FOLD: u32 = {acc};")
    lines.append("")
    here_line = len(lines) + 1
    lines.append("pub fn here() -> u32 { line!() }")
    top_line = lines.index("pub const TOP: u32 = line!();") + 1
    lines.append(f"pub const HERE_MINUS_TOP: u32 = {here_line - top_line};")
    items = "\n".join(lines) + "\n"
    edits = {
        "version": 1,
        "edits": [
            {
                "name": "shift-top",
                "what": "insert one comment line at the top of the big file; every span shifts",
                "path": "src/items.rs",
                "insert_before_line": 1,
                "text": "// shifted by one line\n",
            }
        ],
    }
    return {
        "big-file/src/items.rs": items,
        "big-file/edits.json": json.dumps(edits, indent=2) + "\n",
    }


def generated() -> dict[str, str]:
    files: dict[str, str] = {}
    for part in (deep_vector, trivial_consts, deep_macro, big_file):
        files.update(part())
    return files


def main() -> int:
    inp = parse_input(sys.argv)
    files = generated()
    if inp.mode == "write":
        for rel, text in files.items():
            path = HERE / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel} ({len(text.encode()):,} bytes)")
        return 0
    stale = []
    for rel, text in files.items():
        path = HERE / rel
        if not path.exists():
            stale.append(f"{rel}: missing")
        elif path.read_text() != text:
            stale.append(f"{rel}: differs from gen.py's output")
    for line in stale:
        print(f"gen.py check: {line}", file=sys.stderr)
    if stale:
        print("gen.py check: run `python3 harness/stress-corpus/gen.py '{\"mode\": \"write\"}'`", file=sys.stderr)
        return 1
    print(f"gen.py check: {len(files)} generated files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
