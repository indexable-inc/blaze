#!/usr/bin/env python3
"""First edits after a cold build (lane firstedit-1112, 2026-11-12). Run it on the build VM,
with BLAZE_DUCKDB set to a duckdb binary. One JSON argument:
  {"bin": dir with blaze and blaze-engine, "work": scratch dir, "n": samples (a fresh home and cold
   build each), "edits": body edits after the cold build, "sql": {name: query} run after each
   sample with `debug sql --json`, "keep": keep the last home and daemon, "lock": write the
   Cargo.lock the cold build would write, before it (the control of the lock-file cause)}
Each sample: fresh home, cold `run -q`, wait for an idle daemon, then `edits` body edits, a no-op
run and a comment edit, each timed and checked (exit status and stdout). Prints one JSON line a
sample and a summary."""
import json, os, re, shutil, subprocess, sys, time, hashlib
from dataclasses import dataclass, field

@dataclass(frozen=True)
class In:
    bin: str
    work: str
    n: int = 1
    edits: int = 3
    sql: dict = field(default_factory=dict)
    keep: bool = False
    idle: bool = True
    label: str = ""
    lock: bool = False  # write the Cargo.lock the cold build would, before it

inp = In(**json.loads(sys.argv[1]))
BLAZE = os.path.join(inp.bin, "blaze"); ENGINE = os.path.join(inp.bin, "blaze-engine")
DUCK = os.environ["BLAZE_DUCKDB"]

def env(home):
    return {"HOME": home, "BLAZE_HOME": os.path.join(home, "bh"), "PATH": "/usr/bin:/bin:/run/current-system/sw/bin",
            "TMPDIR": os.path.join(home, "tmp"), "LANG": "C", "RUST_BACKTRACE": "0", "BLAZE_DUCKDB": DUCK}

def run(args, cwd, home, timeout=900):
    s = time.perf_counter()
    r = subprocess.run(args, cwd=cwd, env=env(home), capture_output=True, text=True, timeout=timeout)
    return (time.perf_counter() - s) * 1000, r

def daemons(home):
    pids = []
    for pid in os.listdir("/proc"):
        if not pid.isdigit(): continue
        try:
            if os.readlink(f"/proc/{pid}/exe").endswith("blaze-engine") and \
               f"BLAZE_HOME={home}/bh".encode() in open(f"/proc/{pid}/environ", "rb").read().split(b"\0"):
                pids.append(int(pid))
        except OSError: pass
    return pids

def ticks(pid):
    try:
        f = open(f"/proc/{pid}/stat").read().rsplit(")", 1)[1].split(); return int(f[11]) + int(f[12])
    except OSError: return 0

def quiet(home):
    began = time.time()
    while time.time() - began < 90:
        before = sum(ticks(p) for p in daemons(home)); time.sleep(0.5)
        if sum(ticks(p) for p in daemons(home)) - before <= 1: return time.time() - began
    sys.exit("the daemon was never idle in 90 s")

def stop(home):
    # A daemon is stopped by the blaze that started it (another binary's cannot).
    run([open(os.path.join(home, "inst")).read().strip() + "/blaze", "stop"], home, home)
    began = time.time()
    while daemons(home):
        if time.time() - began > 120: sys.exit(f"daemon outlived stop: {daemons(home)}")
        time.sleep(0.05)

def sql(q, d, home):
    ms, r = run([ENGINE, "debug", "sql", "--json", q], d, home)
    if r.returncode != 0: return {"error": r.stderr[-1500:]}
    return [json.loads(l) for l in r.stdout.splitlines() if l.startswith("{")]

print(json.dumps({"engine_sha256_16": hashlib.sha256(open(ENGINE, "rb").read()).hexdigest()[:16], "bin": inp.bin, "label": inp.label}), flush=True)
rows = []
for i in range(inp.n):
    home = os.path.join(inp.work, f"h{i}")
    if os.path.exists(home): stop(home); shutil.rmtree(home)
    os.makedirs(os.path.join(home, "tmp")); os.makedirs(os.path.join(home, ".blaze"))
    os.symlink("/root/.blaze/native", os.path.join(home, ".blaze/native"))
    open(os.path.join(home, "inst"), "w").write(inp.bin)
    d = os.path.join(home, "hello"); os.makedirs(d + "/src"); src = d + "/src/main.rs"
    open(d + "/Cargo.toml", "w").write('[package]\nname = "hello"\nversion = "0.0.0"\nedition = "2024"\n')
    open(src, "w").write('fn main() {\n    println!("hello: {}", (1..=10).sum::<u32>() + 100);\n}\n')
    if inp.lock:
        open(d + "/Cargo.lock", "w").write('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "hello"\nversion = "0.0.0"\n')
    row = {"sample": i, "bad": 0}
    def step(name, want, args=("run", "-q")):
        ms, r = run([BLAZE, *args], d, home)
        if r.returncode != 0 or want not in r.stdout:
            row["bad"] += 1; print("BAD", name, r.returncode, r.stdout[-300:], r.stderr[-1500:], flush=True)
        row[name] = round(ms, 1)
    step("cold", "hello: 155")
    if inp.idle: row["quiet_s"] = round(quiet(home), 1)
    for e in range(1, inp.edits + 1):
        s = open(src).read()
        with open(src, "r+") as f:
            f.write(re.sub(r"\+ \d+\)", "+ %d)" % (300 + e), s, count=1)); f.truncate()
        step(f"edit{e}", f"hello: {355 + e}")
        if inp.idle: quiet(home)
    step("noop", f"hello: {355 + inp.edits}")
    with open(src, "a") as f: f.write("// c\n")
    step("comment", f"hello: {355 + inp.edits}")
    for name, q in inp.sql.items(): row[name] = sql(q, d, home)
    rows.append(row); print(json.dumps(row), flush=True)
    if not (inp.keep and i == inp.n - 1): stop(home); shutil.rmtree(home)
def med(k):
    xs = sorted(r[k] for r in rows); return {"median": xs[len(xs) // 2], "min": xs[0], "max": xs[-1], "n": len(xs), "over_1s": sum(x > 1000 for x in xs)}
print(json.dumps({"summary": {k: med(k) for k in rows[0] if k not in ("sample", "bad", "quiet_s") and isinstance(rows[0][k], float)}, "bad": sum(r["bad"] for r in rows), "label": inp.label}))
