//! `create table` text for a [`Table`], per engine. The schema is the one source of a table's
//! shape: this text is generated from it, never written by hand, and a driver's `verify` holds
//! a database to the same schema.
//!
//! - Names are double-quoted, a `"` inside doubled, so a name is never read as a keyword.
//! - SQLite: `integer real text blob`; a `Boolean` is `integer` with `check ("col" in (0, 1))`;
//!   the table is `strict`, so SQLite refuses a value of another storage instead of keeping it.
//! - Postgres: `boolean bigint double precision text bytea`; a lone `Integer` primary key is
//!   `bigint generated by default as identity primary key`.
//! - One primary-key column carries `primary key` itself; two or more are a table constraint
//!   `primary key ("a", "b")`, in the schema's column order, on both engines.

#![blaze::sans_io]

use core::fmt;

use crate::desc::{Backend, Storage};
use crate::schema::{Column, Table};

/// Writes `create table` for `table` as `backend`'s text, without a trailing `;`.
pub fn create_table(table: &Table<'_>, backend: Backend, out: &mut impl fmt::Write) -> fmt::Result {
    let keys = table.columns.iter().filter(|column| column.primary_key).count();
    out.write_str("create table ")?;
    quoted(table.name, out)?;
    out.write_str(" (")?;
    for (index, column) in table.columns.iter().enumerate() {
        if index > 0 {
            out.write_str(", ")?;
        }
        column_definition(column, keys == 1, backend, out)?;
    }
    if keys > 1 {
        out.write_str(", primary key (")?;
        let mut first = true;
        for column in table.columns.iter().filter(|column| column.primary_key) {
            if !first {
                out.write_str(", ")?;
            }
            first = false;
            quoted(column.name, out)?;
        }
        out.write_char(')')?;
    }
    out.write_char(')')?;
    if backend == Backend::Sqlite {
        out.write_str(" strict")?;
    }
    Ok(())
}

/// `"col" type [not null] [primary key] [check ..]`. `lone_key`: the table has exactly one
/// primary-key column, which then carries `primary key` itself.
fn column_definition(
    column: &Column<'_>,
    lone_key: bool,
    backend: Backend,
    out: &mut impl fmt::Write,
) -> fmt::Result {
    quoted(column.name, out)?;
    out.write_char(' ')?;
    out.write_str(type_name(column.storage, backend))?;
    let own_key = lone_key && column.primary_key;
    if backend == Backend::Postgres && own_key && column.storage == Storage::Integer {
        // An identity column is never null, and Postgres numbers it when an insert leaves it
        // out, as SQLite does for an `integer primary key`.
        return out.write_str(" generated by default as identity primary key");
    }
    if !column.nullable {
        out.write_str(" not null")?;
    }
    if own_key {
        out.write_str(" primary key")?;
    }
    if backend == Backend::Sqlite && column.storage == Storage::Boolean {
        out.write_str(" check (")?;
        quoted(column.name, out)?;
        out.write_str(" in (0, 1))")?;
    }
    Ok(())
}

fn type_name(storage: Storage, backend: Backend) -> &'static str {
    match (backend, storage) {
        (Backend::Sqlite, Storage::Boolean | Storage::Integer) => "integer",
        (Backend::Sqlite, Storage::Real) => "real",
        (Backend::Sqlite, Storage::Text) => "text",
        (Backend::Sqlite, Storage::Blob) => "blob",
        (Backend::Postgres, Storage::Boolean) => "boolean",
        (Backend::Postgres, Storage::Integer) => "bigint",
        (Backend::Postgres, Storage::Real) => "double precision",
        (Backend::Postgres, Storage::Text) => "text",
        (Backend::Postgres, Storage::Blob) => "bytea",
    }
}

/// `name` in double quotes, each `"` in it doubled.
fn quoted(name: &str, out: &mut impl fmt::Write) -> fmt::Result {
    out.write_char('"')?;
    let mut rest = name;
    while let Some((before, after)) = rest.split_once('"') {
        out.write_str(before)?;
        out.write_str("\"\"")?;
        rest = after;
    }
    out.write_str(rest)?;
    out.write_char('"')
}
