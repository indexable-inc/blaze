//! A scene's numbers, from one file. A `data.json` beside the scene is turned into flecs script constants before the
//! scene loads, so a scene names a figure (`$d_noop_blaze`) and never types one: change the file, render again, and the
//! film shows the new numbers.
//!
//! Every leaf of the JSON becomes `export const d_<path>` (the keys down to it joined by `_`):
//! - a string: the string;
//! - a number: the number, and `d_<path>_t`, its words: digits grouped by three, `decimals` places when the object it
//!   is in says `"decimals"` (else as the file writes it), then a space and the object's `"unit"` when it has one;
//! - a range `{"low": a, "high": b}`: `d_<path>` is `b` (what a bar is drawn to), `d_<path>_low` is `a`, and
//!   `d_<path>_t` is `a–b unit`;
//! - an object with `"compare": ["blaze", "relax"]`: for each name, `d_<path>_<name>_share`, its value over the largest
//!   of them (0 to 1: how long its bar is).
//!
//! `unit`, `decimals` and `compare` are read by this file and are constants too, like any other leaf.
use serde_json::Value;

/// The script for `json` (the text of a data file). Err names the path of what cannot be a constant.
pub fn script(json: &str) -> Result<String, String> {
    let v: Value = serde_json::from_str(json).map_err(|e| e.to_string())?;
    let Value::Object(_) = &v else { return Err("the top level is not an object".into()) };
    let mut out = String::from("// Generated by harness-video (src/data.rs) from the scene's data.json.\n");
    walk("d", &v, &mut out)?;
    Ok(out)
}

fn quote(s: &str) -> String {
    let mut q = String::with_capacity(s.len() + 2);
    q.push('"');
    for c in s.chars() {
        // Flecs script interpolates `$` and `{` in a string, and `\` escapes.
        if matches!(c, '"' | '\\' | '$' | '{') {
            q.push('\\');
        }
        q.push(c);
    }
    q.push('"');
    q
}

/// `1091174` as `1,091,174`; `15.1` as it is.
fn grouped(digits: &str) -> String {
    let (sign, rest) = digits.strip_prefix('-').map_or(("", digits), |r| ("-", r));
    let (whole, frac) = rest.split_once('.').map_or((rest, None), |(w, f)| (w, Some(f)));
    let mut out = String::from(sign);
    for (i, c) in whole.chars().enumerate() {
        if i > 0 && (whole.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    if let Some(f) = frac {
        out.push('.');
        out.push_str(f);
    }
    out
}

fn number(path: &str, n: &Value) -> Result<f64, String> {
    n.as_f64().filter(|f| f.is_finite()).ok_or_else(|| format!("{path}: not a finite number"))
}

/// A number's words: `decimals` places when given, else as the file writes it.
fn words(path: &str, n: &Value, decimals: Option<u64>) -> Result<String, String> {
    let f = number(path, n)?;
    Ok(grouped(&match decimals {
        Some(d) => format!("{f:.*}", d as usize),
        None => n.to_string(),
    }))
}

/// A range `{"low", "high"}` and nothing else.
fn range(v: &Value) -> Option<(&Value, &Value)> {
    let o = v.as_object()?;
    (o.len() == 2).then(|| Some((o.get("low")?, o.get("high")?)))?.filter(|(l, h)| l.is_number() && h.is_number())
}

fn walk(path: &str, v: &Value, out: &mut String) -> Result<(), String> {
    let Value::Object(o) = v else { return Err(format!("{path}: not an object")) };
    let unit = match o.get("unit") {
        None => String::new(),
        Some(Value::String(u)) => format!(" {u}"),
        Some(_) => return Err(format!("{path}_unit: not a string")),
    };
    let decimals = match o.get("decimals") {
        None => None,
        Some(d) => Some(d.as_u64().filter(|d| *d <= 6).ok_or_else(|| format!("{path}_decimals: not 0 to 6"))?),
    };
    // What a member is worth as a bar: a number, or a range's high end.
    let worth = |name: &str| -> Result<f64, String> {
        let p = format!("{path}_{name}");
        match o.get(name) {
            Some(n) if n.is_number() => number(&p, n),
            Some(r) => match range(r) {
                Some((_, high)) => number(&p, high),
                None => Err(format!("{p}: compared, but not a number or a range")),
            },
            None => Err(format!("{p}: compared, but not there")),
        }
    };
    for (key, value) in o {
        if !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') || key.is_empty() {
            return Err(format!("{path}: key {key:?} is not letters, digits and _"));
        }
        let p = format!("{path}_{key}");
        match value {
            Value::String(s) => out.push_str(&format!("export const {p} = {}\n", quote(s))),
            Value::Number(_) => {
                out.push_str(&format!("export const {p}: f32 = {}\n", number(&p, value)?));
                if !matches!(key.as_str(), "decimals") {
                    out.push_str(&format!("export const {p}_t = {}\n", quote(&(words(&p, value, decimals)? + &unit))));
                }
            }
            Value::Object(_) => match range(value) {
                Some((low, high)) => {
                    out.push_str(&format!("export const {p}: f32 = {}\n", number(&p, high)?));
                    out.push_str(&format!("export const {p}_low: f32 = {}\n", number(&p, low)?));
                    let t = format!("{}\u{2013}{}{unit}", words(&p, low, decimals)?, words(&p, high, decimals)?);
                    out.push_str(&format!("export const {p}_t = {}\n", quote(&t)));
                }
                None => walk(&p, value, out)?,
            },
            Value::Array(names) if key == "compare" => {
                let names: Vec<&str> = names
                    .iter()
                    .map(|n| n.as_str().ok_or_else(|| format!("{p}: not a list of member names")))
                    .collect::<Result<_, _>>()?;
                let worths: Vec<f64> = names.iter().map(|n| worth(n)).collect::<Result<_, _>>()?;
                let most = worths.iter().copied().fold(0.0, f64::max);
                if !(most > 0.0) {
                    return Err(format!("{p}: nothing compared is above 0"));
                }
                for (name, w) in names.iter().zip(&worths) {
                    out.push_str(&format!("export const {path}_{name}_share: f32 = {}\n", w / most));
                }
            }
            other => return Err(format!("{p}: {other} cannot be a constant (a string, a number, a range or an object can)")),
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Each kind of leaf becomes the constants the module doc says, a file's own digits are kept, and what cannot be a
    /// constant is refused by its path.
    #[test]
    fn leaves_become_constants() {
        let s = script(
            r#"{"when": "2026-11-11", "row": {"unit": "ms", "compare": ["blaze", "relax"], "blaze": 15.1,
                "relax": {"low": 58, "high": 89}}, "n": {"before": 1091174, "cold": {"decimals": 2, "unit": "s", "relax": 0.3}}}"#,
        )
        .unwrap_or_else(|e| panic!("{e}"));
        for line in [
            "export const d_when = \"2026-11-11\"",
            "export const d_row_blaze: f32 = 15.1",
            "export const d_row_blaze_t = \"15.1 ms\"",
            "export const d_row_relax: f32 = 89",
            "export const d_row_relax_low: f32 = 58",
            "export const d_row_relax_t = \"58\u{2013}89 ms\"",
            "export const d_row_relax_share: f32 = 1",
            "export const d_n_before_t = \"1,091,174\"",
            "export const d_n_cold_relax_t = \"0.30 s\"",
        ] {
            assert!(s.lines().any(|l| l == line), "no line {line:?} in:\n{s}");
        }
        let share = s.lines().find_map(|l| l.strip_prefix("export const d_row_blaze_share: f32 = ")).unwrap_or_else(|| panic!("{s}"));
        assert!((share.parse::<f64>().unwrap_or(0.0) - 15.1 / 89.0).abs() < 1e-9, "{share}");
        assert!(script(r#"{"a": {"b": [1, 2]}}"#).is_err_and(|e| e.starts_with("d_a_b:")));
        assert!(script(r#"{"a": {"compare": ["x"]}}"#).is_err_and(|e| e.contains("d_a_x")));
    }
}
