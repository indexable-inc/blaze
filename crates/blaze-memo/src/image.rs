/// What a crate's image answers while a command runs ([`Memo::serve`]): the driver's records
/// and the facts of the snapshot.
pub trait Image: Sync {
    /// The toolchain every record's key starts from.
    fn tool(&self) -> ToolId;
    /// The record of kind [`MemoEntry`] filed under `key` for arena index `arena`, if any.
    fn record(&self, arena: u32, key: &Key<MemoEntry>) -> Option<&[u8]>;
    /// The digest fact `id` has in this snapshot; `None` where it is gone. Answers both input
    /// facts and the stable facts [`Image::query_fact`] gives.
    fn now(&self, id: ContentId) -> Option<ContentId>;
    /// The stable fact a [`Read::Query`] row of `memo` stands for in a filed list (a fact
    /// boundary's: blaze-item-hash gives the item's hash fact, its id the item's stable name and
    /// its digest the hash). `None` where `row` is of a kind this image does not translate.
    fn query_fact(&self, memo: &Memo, row: Read) -> Option<Fact>;
}

/// An [`Image`] of a records memo (the driver's `Resident`), a function giving the facts now,
/// and one translating a boundary row ([`Image::query_fact`]).
pub struct ImageOf<'a, M, F, Q> {
    pub tool: ToolId,
    pub records: &'a M,
    pub now: F,
    pub query: Q,
}

impl<M, F, Q> Image for ImageOf<'_, M, F, Q>
where
    M: Records + Sync,
    F: Fn(ContentId) -> Option<ContentId> + Sync,
    Q: Fn(&Memo, Read) -> Option<Fact> + Sync,
{
    fn tool(&self) -> ToolId {
        self.tool
    }

    fn record(&self, arena: u32, key: &Key<MemoEntry>) -> Option<&[u8]> {
        self.records.get::<MemoEntry>(arena, key)
    }

    fn now(&self, id: ContentId) -> Option<ContentId> {
        (self.now)(id)
    }

    fn query_fact(&self, memo: &Memo, row: Read) -> Option<Fact> {
        (self.query)(memo, row)
    }
}

/// A key's stable form: the same bytes for the same item in every snapshot and process, what
/// an image record is filed under. An input is written as its fact id (generated by
/// `#[blaze_memo::input]`); plain data as its bytes; an interned id has no stable form (its
/// index follows timing): key an imaged query by stable ids instead.
pub trait Stable {
    fn stable(&self, memo: &Memo, out: &mut StableKey);
}

/// The bytes a [`Stable`] key writes: each part fixed-width or length-prefixed, so two field
/// lists never write alike.
pub struct StableKey(Vec<u8, Global>);

impl StableKey {
    pub(crate) fn new() -> StableKey {
        StableKey(Vec::new_in(Global))
    }

    pub fn bytes(&mut self, bytes: &[u8]) {
        self.u64(bytes.len() as u64);
        self.0.extend_from_slice(bytes);
    }

    pub fn u64(&mut self, value: u64) {
        self.0.extend_from_slice(&value.to_le_bytes());
    }

    pub fn id(&mut self, id: &ContentId) {
        self.0.extend_from_slice(&id.0);
    }

    pub(crate) fn as_slice(&self) -> &[u8] {
        &self.0
    }
}

macro_rules! stable_int {
    ($($ty:ty),* $(,)?) => {$(
        impl Stable for $ty {
            #[inline]
            fn stable(&self, _: &Memo, out: &mut StableKey) {
                out.0.extend_from_slice(&self.to_le_bytes());
            }
        }
    )*};
}

stable_int!(u8, u16, u32, u64, u128, usize, i8, i16, i32, i64, i128, isize);

impl Stable for bool {
    fn stable(&self, _: &Memo, out: &mut StableKey) {
        out.0.push(u8::from(*self));
    }
}

impl Stable for char {
    fn stable(&self, _: &Memo, out: &mut StableKey) {
        out.0.extend_from_slice(&u32::from(*self).to_le_bytes());
    }
}

impl Stable for () {
    fn stable(&self, _: &Memo, _: &mut StableKey) {}
}

impl Stable for str {
    fn stable(&self, _: &Memo, out: &mut StableKey) {
        out.bytes(self.as_bytes());
    }
}

impl Stable for ContentId {
    fn stable(&self, _: &Memo, out: &mut StableKey) {
        out.id(self);
    }
}

impl Stable for Fact {
    fn stable(&self, _: &Memo, out: &mut StableKey) {
        out.id(&self.id);
        out.id(&self.digest);
    }
}

impl<T: Stable + ?Sized> Stable for &T {
    fn stable(&self, memo: &Memo, out: &mut StableKey) {
        (**self).stable(memo, out);
    }
}

impl<T: Stable> Stable for [T] {
    fn stable(&self, memo: &Memo, out: &mut StableKey) {
        out.u64(self.len() as u64);
        for it in self {
            it.stable(memo, out);
        }
    }
}

impl<T: Stable, const N: usize> Stable for [T; N] {
    fn stable(&self, memo: &Memo, out: &mut StableKey) {
        for it in self {
            it.stable(memo, out);
        }
    }
}

impl<T: Stable> Stable for Option<T> {
    fn stable(&self, memo: &Memo, out: &mut StableKey) {
        match self {
            None => out.0.push(0),
            Some(it) => {
                out.0.push(1);
                it.stable(memo, out);
            }
        }
    }
}

macro_rules! stable_tuple {
    ($($name:ident),+) => {
        impl<$($name: Stable),+> Stable for ($($name,)+) {
            #[allow(non_snake_case)]
            fn stable(&self, memo: &Memo, out: &mut StableKey) {
                let ($($name,)+) = self;
                $($name.stable(memo, out);)+
            }
        }
    };
}

