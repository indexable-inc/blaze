/// A variable-length byte-backed value that can be imaged through [`Imaged::for_bytes`] without
/// requiring fixed-size `blaze_format::Record::PLAIN`.
pub trait ImagedBytes: Sized {
    fn as_imaged_bytes(&self) -> &[u8];
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self>;
}

impl ImagedBytes for Vec<u8> {
    fn as_imaged_bytes(&self) -> &[u8] {
        self.as_slice()
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        Some(bytes.to_vec())
    }
}

impl ImagedBytes for Box<[u8]> {
    fn as_imaged_bytes(&self) -> &[u8] {
        self
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        Some(Box::from(bytes))
    }
}

impl ImagedBytes for std::sync::Arc<[u8]> {
    fn as_imaged_bytes(&self) -> &[u8] {
        self
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        Some(std::sync::Arc::from(bytes))
    }
}

impl ImagedBytes for String {
    fn as_imaged_bytes(&self) -> &[u8] {
        self.as_bytes()
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        std::str::from_utf8(bytes).ok().map(str::to_owned)
    }
}

impl ImagedBytes for Box<str> {
    fn as_imaged_bytes(&self) -> &[u8] {
        self.as_bytes()
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        std::str::from_utf8(bytes).ok().map(Box::from)
    }
}

impl ImagedBytes for std::sync::Arc<str> {
    fn as_imaged_bytes(&self) -> &[u8] {
        self.as_bytes()
    }
    fn from_imaged_bytes(bytes: &[u8]) -> Option<Self> {
        std::str::from_utf8(bytes).ok().map(std::sync::Arc::from)
    }
}

/// What an imaged query gives `fetch`: its key's stable form and its value's bytes both ways.
/// Made only where the bounds hold ([`Imaged::new`] or [`Imaged::for_bytes`]), so `fetch` needs
/// none.
pub struct Imaged<K, V> {
    stable: fn(&K, &Memo, &mut StableKey),
    encode: fn(&V) -> &[u8],
    decode: fn(&[u8]) -> Option<V>,
    _of: PhantomData<fn(K) -> V>,
}

impl<K: Stable, V> Imaged<K, V> {
    /// Builds an [`Imaged`] codec from explicit byte encode/decode functions (for variable-length
    /// or custom byte-serialized query values).
    pub const fn from_codec(encode: fn(&V) -> &[u8], decode: fn(&[u8]) -> Option<V>) -> Imaged<K, V> {
        fn stable<K: Stable>(key: &K, memo: &Memo, out: &mut StableKey) {
            key.stable(memo, out);
        }
        Imaged { stable: stable::<K>, encode, decode, _of: PhantomData }
    }
}

impl<K: Stable, V: ImagedBytes> Imaged<K, V> {
    /// Builds an [`Imaged`] adapter for any variable-length [`ImagedBytes`] value.
    pub const fn for_bytes() -> Imaged<K, V> {
        Self::from_codec(V::as_imaged_bytes, V::from_imaged_bytes)
    }
}

impl<K: Stable, V: blaze_format::Record> Imaged<K, V> {
    pub const fn new() -> Imaged<K, V> {
        const {
            assert!(
                <V as blaze_format::Record>::PLAIN,
                "an imaged query's value is a plain record (`blaze_format::Record::PLAIN`): \
                 every bit pattern a value and nothing to follow, so its bytes are the value"
            )
        };
        fn encode<V: blaze_format::Record>(value: &V) -> &[u8] {
            blaze_format::bytes_of_slice(std::slice::from_ref(value))
        }
        fn decode<V: blaze_format::Record>(bytes: &[u8]) -> Option<V> {
            (bytes.len() == size_of::<V>()).then(|| {
                // SAFETY: `size_of::<V>()` bytes, and `V` is plain: every bit pattern of its
                // size is a value (`Record::PLAIN`), so any bytes read are one.
                unsafe { ptr::read_unaligned(bytes.as_ptr().cast::<V>()) }
            })
        }
        Self::from_codec(encode::<V>, decode::<V>)
    }
}

impl<K: Stable, V: blaze_format::Record> Default for Imaged<K, V> {
    fn default() -> Self {
        Imaged::new()
    }
}

/// The image a [`Memo::serve`] scope lends, as a pointer to its stack, and who is reading it.
pub(crate) struct Serving {
    at: AtomicPtr<Served>,
    readers: AtomicU32,
}

struct Served {
    /// The lent image, its lifetime erased: read only while `readers` counts the reader and
    /// `at` points here, both of which the scope's end waits out.
    image: *const (dyn Image + 'static),
}

/// How long [`Memo::serve`]'s end waits for a probe still reading, in spins of a few
/// nanoseconds: a probe holds the image across one lookup and one read list, never a run.
const UNSERVE_SPINS: u64 = 1 << 32;

impl Serving {
    pub(crate) const fn none() -> Serving {
        Serving { at: AtomicPtr::new(ptr::null_mut()), readers: AtomicU32::new(0) }
    }

    /// `f` on the image lent now, or `None` outside a [`Memo::serve`].
    fn with<R>(&self, f: impl FnOnce(&dyn Image) -> Option<R>) -> Option<R> {
        struct Out<'a>(&'a AtomicU32);
        impl Drop for Out<'_> {
            fn drop(&mut self) {
                self.0.fetch_sub(1, Ordering::AcqRel);
            }
        }
        self.readers.fetch_add(1, Ordering::SeqCst);
        let _out = Out(&self.readers);
        let at = self.at.load(Ordering::SeqCst);
        if at.is_null() {
            return None;
        }
        // SAFETY: `at` is the `Served` on the stack of the `serve` call that stored it; that
        // call clears `at` and waits until no reader counted before the clear is left, so the
        // `Served` and the image it lends outlive this read.
        let image = unsafe { &*(*at).image };
        f(image)
    }
}

/// The records imaged runs filed in a snapshot, for [`Memo::file_records`].
pub(crate) struct Outbox(SegQueue<Filed, Global>);

impl Outbox {
    pub(crate) fn new() -> Outbox {
        Outbox(SegQueue::new())
    }
}

struct Filed {
    arena: u32,
    key: Key<MemoEntry>,
    bytes: Vec<u8>,
}

impl Memo {
    /// Runs `f` (a command's work: every task asking this snapshot's queries ends inside it)
    /// with `image` lent to imaged queries: a miss looks its record up there first, and a run
    /// files its record for [`Memo::file_records`]. Outside a `serve`, an imaged query neither
    /// looks up nor files.
    ///
    /// # Panics
    ///
    /// Where the snapshot keeps no read lists ([`crate::Reads::Off`]: a record is valid only
    /// by its read list), or a `serve` of it is running already.
    pub fn serve<R>(&self, image: &dyn Image, f: impl FnOnce() -> R) -> R {
        assert!(
            self.keeps_reads(),
            "`Memo::serve` on a snapshot that keeps no read lists (`Reads::Off`): an image \
             record is valid by its read list, so make it with `Reads::Kept`"
        );
        // SAFETY: lifetime erasure only; `Served::image` says why the image outlives its reads.
        let image = unsafe {
            std::mem::transmute::<*const (dyn Image + '_), *const (dyn Image + 'static)>(
                ptr::from_ref(image),
            )
        };
        let served = Served { image };
        let at = ptr::from_ref(&served).cast_mut();
        assert!(
            self.image
                .at
                .compare_exchange(ptr::null_mut(), at, Ordering::SeqCst, Ordering::SeqCst)
                .is_ok(),
            "`Memo::serve` inside another `serve` of the same snapshot"
        );
        struct End<'a>(&'a Serving);
        impl Drop for End<'_> {
            fn drop(&mut self) {
                self.0.at.store(ptr::null_mut(), Ordering::SeqCst);
                let mut spins = 0_u64;
                while self.0.readers.load(Ordering::SeqCst) != 0 {
                    spins += 1;
                    assert!(
                        spins < UNSERVE_SPINS,
                        "an image probe held the lent image for {UNSERVE_SPINS} spins after its \
                         `serve` ended: a probe ran user code or stopped"
                    );
                    std::hint::spin_loop();
                }
            }
        }
        let _end = End(&self.image);
        f()
    }

    /// Files every record imaged runs made in this snapshot so far into `records`, each with
    /// the proof its one key check makes in `snap` (`blaze_keyed::proof::hit`), and gives how
    /// many. The driver calls it between commands, holding its records memo.
    ///
    /// # Panics
    ///
    /// Where a record written here does not open under its own key: a bug in this module.
    pub fn file_records<M: Records>(&self, snap: Snapshot<'_>, records: &mut M) -> usize {
        let mut filed = 0;
        while let Some(it) = self.filed.0.pop() {
            let hit = proof::hit(snap, it.key, &it.bytes).unwrap_or_else(|error| {
                panic!("an image record written under {:?} does not open under it: {error}", it.key)
            });
            records.keep::<MemoEntry>(it.arena, &hit.holds(), &it.bytes);
            filed += 1;
        }
        filed
    }
}

fn entry_key<K, V>(
    memo: &Memo,
    tool: ToolId,
    kind: &'static Kind,
    key: &K,
    imaged: &Imaged<K, V>,
) -> Key<MemoEntry> {
    let mut stable = StableKey::new();
    (imaged.stable)(key, memo, &mut stable);
    MemoEntry::key(&MemoEntryInputs { tool, query: kind.id(), key: stable.as_slice() })
}

/// On a miss of an imaged query in a [`Memo::serve`]: its record, if one is filed under its key
/// and its read list holds now, published as the entry (with that read list, replayed into the
/// asker). `None`: run it.
///
/// # Panics
///
/// Where a record filed under the key does not open as one, or its value has another size:
/// a record the store holds under a key is the one written under it (no fallback, rule 3).
pub(crate) fn probe<'db, K: Copy + Eq + Debug + crate::Home + 'static, V: 'static>(
    memo: &'db Memo,
    slot: &'db Slot,
    kind: &'static Kind,
    hash: u64,
    key: &K,
    imaged: &Imaged<K, V>,
) -> Option<&'db V> {
    let entry = memo.image.with(|image| {
        let record_key = entry_key(memo, image.tool(), kind, key, imaged);
        let bytes = image.record(slot.id.index(), &record_key)?;
        let named = || {
            let mut out = String::new();
            crate::task::write_key(&mut out, kind, key);
            out
        };
        let root = record::open::<MemoEntry>(bytes, &record_key).unwrap_or_else(|error| {
            panic!("the image record of {} does not open under its key: {error}", named())
        });
        let reads = root.reads.follow(bytes).unwrap_or_else(|error| {
            panic!("the image record of {} has no read list: {error}", named())
        });
        let payload = root.payload.follow(bytes).unwrap_or_else(|error| {
            panic!("the image record of {} has no value: {error}", named())
        });
        // The read list's one check in this snapshot: after it the value is an entry, and an
        // entry is hit with no check.
        counts::image_check();
        if memo.plant() != crate::Plant::ImageSkipsVerify
            && reads.iter().any(|read| image.now(read.id) != Some(read.digest))
        {
            counts::image_redo();
            return None;
        }
        let value = (imaged.decode)(payload).unwrap_or_else(|| {
            panic!(
                "the image record of {} holds {} bytes, not the {} of its value",
                named(),
                payload.len(),
                size_of::<V>()
            )
        });
        mark_borrows(memo, slot, key, &|out: &mut dyn std::fmt::Write| crate::task::write_key(out, kind, key));
        // The record's facts, as this entry's rows: what a reader of it now depends on (the
        // same facts the check above compared).
        let boundary = boundary_local(memo, slot, kind);
        // The record's facts are its whole flat list (sorted and merged when filed): direct
        // rows with no callees. Scratch on the global heap, copied once into the arena.
        let mut rows = Vec::with_capacity_in(reads.len(), Global);
        rows.extend(reads.iter().map(|fact| Read::Input { kind: KindId::of(&crate::IMAGE_FACT), fact: *fact }));
        let entry = with_local(slot, |local| -> *const Entry<K, V> {
            let lists = crate::record::Lists::in_arena(slot, local, &rows, &[]);
            let at = boundary.map_or(0, |(_, at)| at);
            local.alloc(Entry { head: Head::listed(hash, kind, lists, at), key: *key, value })
        });
        // SAFETY: just made in `slot`'s arena, which `memo` holds.
        let entry: &Entry<K, V> = unsafe { &*entry };
        if let Some((column, at)) = boundary {
            column.set_local(at, &entry.head);
        }
        Some(entry)
    })?;
    if publish::<K, V>(memo, slot, &entry.head).is_err() {
        panic!(
            "{}({:?}) was served twice in one snapshot: two probes of one key passed the flight",
            kind.name(),
            crate::Bounded::key(key)
        );
    }
    counts::image_served();
    counts::completed_one();
    task::pass_on(memo, slot.id, &entry.head);
    Some(&entry.value)
}

/// After a run of an imaged query computed `value` as itself (no cycle), its entry `head`
/// published: its record, queued for [`Memo::file_records`]. Nothing is filed outside a
/// [`Memo::serve`] (and no flat list made for it there), and nothing for a list holding an
/// untracked read ([`crate::read_untracked`]: valid in this snapshot only, so the entry is
/// recomputed in each; counted, `image_untracked`, inside a serve).
///
/// The filed list is the entry's flat list ([`crate::record::flat_of`], made here and kept
/// with the entry) as stable facts: an input row's fact as it is, a boundary row
/// ([`Read::Query`]) as the image translates it ([`Image::query_fact`]); duplicates merged.
///
/// # Panics
///
/// Where the image translates no fact for a boundary row: the record would hold a read it
/// cannot check, so the image must translate every boundary it is lent with.
pub(crate) fn file<K, V>(
    memo: &Memo,
    slot: &Slot,
    kind: &'static Kind,
    key: &K,
    value: &V,
    head: &Head,
    imaged: &Imaged<K, V>,
) {
    let mut untracked = false;
    let mut backdated = false;
    let made = memo.image.with(|image| {
        let reads = crate::record::flat_of(memo, head);
        if reads.iter().any(|read| read.is_untracked()) {
            untracked = true;
            return None;
        }
        let record_key = entry_key(memo, image.tool(), kind, key, imaged);
        let payload = (imaged.encode)(value);
        // Output-fingerprint early cutoff (backdating): when recomputing after a read digest
        // moved produces the exact same serialized value bytes as the previous record, skip
        // redundant record serialization and re-filing.
        if let Some(prev_bytes) = image.record(slot.id.index(), &record_key)
            && let Ok(prev_root) = record::open::<MemoEntry>(prev_bytes, &record_key)
            && let Ok(prev_payload) = prev_root.payload.follow(prev_bytes)
            && prev_payload == payload
        {
            backdated = true;
            return None;
        }
        let mut facts = Vec::with_capacity_in(reads.len(), Global);
        for read in reads {
            facts.push(match *read {
                Read::Input { fact, .. } => fact,
                Read::Query { kind: of, key: at } => image.query_fact(memo, *read).unwrap_or_else(|| {
                    panic!(
                        "{} read boundary {of:?} ({at:?}), which the lent image translates to no \
                         stable fact (`Image::query_fact`): its record could not be checked",
                        kind.name()
                    )
                }),
            });
        }
        facts.sort_unstable();
        facts.dedup();
        let bytes = record::write_traced(&record_key, &facts, &[], payload);
        Some(Filed { arena: slot.id.index(), key: record_key, bytes })
    });
    if untracked {
        counts::image_untracked();
    } else if backdated {
        counts::image_backdated();
    }
    if let Some(filed) = made {
        counts::image_filed();
        memo.filed.0.push(filed);
    }
}
