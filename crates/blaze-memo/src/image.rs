//! The crate's own image: a record per entry of an imaged query (`#[tracked(image)]`) of the
//! crate being built, which outlives the crate's arena (spec front-end-on-memo F).
//!
//! An edit drops the edited crate's whole arena (decision 4), so without more every item of
//! the crate would run again: O(crate), not O(edit). An imaged query's entry is therefore also
//! written as a record of kind [`MemoEntry`] (its key: the toolchain, the query, the key's
//! [`Stable`] bytes; its read list; its value's bytes), which the driver files in its records
//! memo through `blaze_keyed::memo::Memo::keep` ([`Memo::file_records`], with the proof the
//! record's one key check makes). After the arena is dropped and made again, a miss of an
//! imaged query looks its record up first ([`Memo::serve`] gives the records and the facts
//! now): found under its key, its read list is checked once against the facts now; every
//! digest equal and the value is the entry, published with that read list, and nothing checks
//! it again in that snapshot or any that carries the arena (decision 18: a read list is
//! verified at most once per (item, snapshot)); a digest that moved and the query runs. So an
//! edit reruns the items whose reads moved and their readers, plus one probe per demanded
//! item.
//!
//! What may be imaged: a query whose key is [`Stable`] (inputs by their fact id, data by its
//! bytes; an interned id is not, until it has a stable form) and whose value is a plain
//! `blaze_format::Record` (no pointer, no id, no padding: its bytes are the value). A run of an
//! imaged query reads only its home arena and the arenas in its home's declared closure
//! ([`crate::Inputs::borrows`]), checked where the read is noted: a served entry sets no
//! borrow bits, and the closure is what keeps it sound to carry (any of those dropped drops
//! the home, by its declared borrows).
//!
//! Only a value a run computed as itself is filed: a cycle's head or member value depends on
//! the path the cycle was entered by, and is never filed.

