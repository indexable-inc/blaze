//! Interning per arena: a value's id is (its home arena, an index there).
//!
//! What replaces the process-global interner: each arena interns the values homed in it (the
//! greatest arena their fields name), in its own table, with indices from its own counter. A
//! hit is a table lookup and writes nothing; a miss takes an index (one atomic add on the
//! arena's counter, not a global one), keeps the value's head in the arena's column, then
//! publishes it; a lost race leaves an index unused. Ids are dense per arena but their order
//! follows timing: never order output by them.

use std::hash::Hash;

use crate::{
    Gid, Home, Kind, Memo,
    arena::with_local,
    counts,
    fetch::{hash_of, lookup, publish},
    home::{home_of, mark_borrows},
    task,
    trie::{Entry, Head},
};

/// An interned struct: generated by `#[blaze_memo::interned]`.
pub trait Interned: 'static {
    /// The fields, in their stored form. Owns no memory to drop.
    type Fields: Eq + Hash + Home + Send + Sync + 'static;
    const KIND: &'static Kind;
}

/// The id of `fields`, interned in their home arena.
pub fn intern<T: Interned>(memo: &Memo, fields: T::Fields) -> Gid {
    const { crate::plumbing::assert_no_drop::<T::Fields>() };
    let slot = memo.slot(home_of(&fields));
    task::note_read_of(memo, slot);
    let hash = hash_of(T::KIND, &fields);
    if let Some(head) = lookup::<T::Fields, ()>(memo, slot, T::KIND, hash, &fields) {
        counts::hit();
        return gid_of(slot.id, head);
    }
    counts::miss();
    mark_borrows(memo, slot, &fields);
    let spill = !slot.writable_by(memo.epoch());
    let column = if spill { memo.spill() } else { slot };
    let local = column.reserve_local(spill);
    let entry = with_local(slot, |at| -> *const Entry<T::Fields, ()> {
        at.alloc(Entry { head: Head::new(hash, T::KIND, &[], local), key: fields, value: () })
    });
    // SAFETY: just made in `slot`'s arena, which `memo` holds.
    let entry = unsafe { &*entry };
    // The column first: whoever finds the entry may look its id up at once.
    column.set_local(local, &entry.head);
    match publish::<T::Fields, ()>(memo, slot, &entry.head) {
        Ok(()) => gid_of(slot.id, &entry.head),
        // Interned by another task first, or (after a successor took the arena) found in the
        // spill table: that one's id.
        Err(theirs) => gid_of(slot.id, theirs),
    }
}

fn gid_of(arena: crate::ArenaId, head: &Head) -> Gid {
    Gid::new(arena, head.local)
}

/// The fields `id` was interned with.
///
/// # Panics
///
/// Where `id` is of another struct (a kind other than `T`'s), or dead.
pub fn interned<'db, T: Interned>(memo: &'db Memo, id: Gid) -> &'db T::Fields {
    let head = memo.head_of(id);
    if !id.is_spill() {
        task::note_read_of(memo, memo.slot(id.arena()));
    }
    assert!(
        std::ptr::eq(head.kind, T::KIND),
        "{id:?} is a {}, not a {}",
        head.kind.name(),
        T::KIND.name()
    );
    // SAFETY: an entry of `T::KIND` is an `Entry<T::Fields, ()>`.
    &unsafe { Entry::<T::Fields, ()>::of(head) }.key
}
