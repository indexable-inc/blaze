//! What tests of crates on the memo ask that the old engine's event log and value counts told
//! them: which `(query, key)` ran in a snapshot, in order ([`RunLog`], given to a snapshot with
//! [`crate::Builder::log_runs`]), and how many entries of a query an arena holds
//! ([`crate::Memo::entries`]). Not behind `cfg(test)`: other crates' tests use it. A snapshot
//! without a log pays one branch per run; with one, a run costs a copy of its key on the
//! global heap (one `Arc` of the key) and one [`Ran`] pushed under the log's lock. Nothing is
//! formatted when a run starts: a key's `Debug` may need the database attached (an id prints
//! its fields through [`crate::attach`], and hir-ty's solver ids refuse to print without it),
//! and a run starts with none. A row is rendered as text only when it is read
//! ([`Ran::key`], `Debug`), by the reader, inside `attach`.

use std::{
    alloc::{Allocator, Global},
    any::Any,
    fmt, ptr,
    sync::Arc,
};

use blaze_core::lock::Lock;

use crate::{ArenaId, Kind, Query};

/// One run: the query, the arena its entry is homed in, and its key, typed. The text of the
/// key is not kept: [`Ran::key`] writes it when asked, with what the asker has attached.
#[derive(Clone)]
pub struct Ran {
    /// The query's full path (`module::f`, `module::Type::method`, as [`Kind::name`]).
    pub query: &'static str,
    kind: &'static Kind,
    arena: ArenaId,
    key: Arc<dyn Any + Send + Sync, Global>,
    /// Writes `key` as `name(key)` ([`crate::task::write_key`]); `key` is the query's key type.
    render: fn(&'static Kind, &dyn Any, &mut dyn fmt::Write),
    /// Whether two keys of this query's key type are equal.
    same: fn(&dyn Any, &dyn Any) -> bool,
}

/// [`Ran::render`] for a query whose key type is `K`.
fn render_key<K: fmt::Debug + 'static>(kind: &'static Kind, key: &dyn Any, out: &mut dyn fmt::Write) {
    let key = key.downcast_ref::<K>().expect("a run's key is its query's key type");
    crate::task::write_key(out, kind, key);
}

/// [`Ran::same`] for a query whose key type is `K`.
fn same_key<K: Eq + 'static>(a: &dyn Any, b: &dyn Any) -> bool {
    a.downcast_ref::<K>() == b.downcast_ref::<K>()
}

impl Ran {
    /// The key as `name(key)`, written now by its `Debug`. Ask inside
    /// [`crate::attach`] of the snapshot the run was in (or a later one that still holds its
    /// arena): an id prints its fields only with a database attached, and some ids' `Debug`
    /// refuses to print without one.
    pub fn key(&self) -> String {
        let mut out = String::new();
        (self.render)(self.kind, &*self.key, &mut out);
        out
    }

    /// The arena the run's entry is homed in (its key's [`crate::Home`]).
    pub fn arena(&self) -> ArenaId {
        self.arena
    }

    /// Whether this was a run of the tracked fn `Q` (its generated struct: `q`, or
    /// `Type_method` for a method) for `args`: the arguments after `db` in their stored form,
    /// as a tuple (`(id,)` for one), as `Q::key_of` gives them.
    ///
    /// # Panics
    ///
    /// Where `args` is not `Q`'s argument tuple, naming the query and the type it takes: a
    /// test asking with the wrong type would otherwise be told `false` forever.
    pub fn is<Q: Logged>(&self, args: &impl Any) -> bool {
        Q::ran_with(self, args)
    }

    /// The key of this run, when it was a run of `kind` with key type `K`.
    fn key_of<K: 'static>(&self, kind: &'static Kind) -> Option<&K> {
        if ptr::eq(self.kind, kind) { self.key.downcast_ref::<K>() } else { None }
    }
}

/// A tracked fn's generated struct, as [`Ran::is`] asks it (generated by `#[tracked]`).
pub trait Logged {
    /// Whether `ran` was a run of this query for `args` (its argument tuple; any other type
    /// panics, see [`Ran::is`]).
    fn ran_with(ran: &Ran, args: &dyn Any) -> bool;
}

/// The key of `ran` when it ran `kind`, whose key type is `K` (the generated `ran_with`).
#[doc(hidden)]
pub fn ran_key<'r, K: 'static>(ran: &'r Ran, kind: &'static Kind) -> Option<&'r K> {
    ran.key_of::<K>(kind)
}

/// [`Ran::is`] was given a value that is not the query's argument tuple.
#[doc(hidden)]
#[track_caller]
pub fn wrong_args(query: &'static str, takes: &'static str) -> ! {
    panic!("`Ran::is::<{query}>` takes its stored argument tuple `{takes}`: another type never matches")
}

impl PartialEq for Ran {
    /// By query, arena and typed key (the key type's `Eq`): no text is made to compare.
    fn eq(&self, other: &Ran) -> bool {
        ptr::eq(self.kind, other.kind)
            && self.arena == other.arena
            && (self.same)(&*self.key, &*other.key)
    }
}

impl Eq for Ran {}

/// Renders the key now ([`Ran::key`]): print a run inside [`crate::attach`].
impl fmt::Debug for Ran {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} in {:?}", self.key(), self.arena)
    }
}

/// The runs of the snapshots a log was given to, in the order they started.
pub struct RunLog {
    runs: Lock<Vec<Ran, Global>>,
}

impl Default for RunLog {
    fn default() -> Self {
        RunLog::new()
    }
}

impl RunLog {
    pub fn new() -> RunLog {
        RunLog { runs: Lock::new("blaze-memo run log", Vec::new_in(Global)) }
    }

    /// Logs a run of `Q` for `key`, homed in `arena`: the key is copied, never formatted (see
    /// the module doc). `plant` is the snapshot's: [`crate::Plant::LogFormatsEagerly`] writes
    /// the key's text here, at the run's start, as the log did before rows were rendered on
    /// read.
    pub(crate) fn push<Q: Query>(&self, arena: ArenaId, key: &Q::Key, plant: crate::Plant) {
        let key: Arc<dyn Any + Send + Sync, Global> = Arc::new_in(*key, Global);
        let ran = Ran {
            query: Q::KIND.name(),
            kind: Q::KIND,
            arena,
            key,
            render: render_key::<Q::Key>,
            same: same_key::<Q::Key>,
        };
        if plant == crate::Plant::LogFormatsEagerly {
            std::hint::black_box(ran.key());
        }
        self.runs.lock().push(ran);
    }

    /// The runs so far, emptied.
    pub fn take(&self) -> Vec<Ran, Global> {
        std::mem::replace(&mut *self.runs.lock(), Vec::new_in(Global))
    }

    /// How many runs so far were of the query named `query` (its full path).
    pub fn count(&self, query: &str) -> usize {
        self.runs.lock().iter().filter(|it| it.query == query).count()
    }
}

/// The flat read list of the boundary entry a [`crate::Read::Query`] row names (`row` from a
/// [`crate::record`] in `memo`): what a test compares a boundary's own reads against, which
/// its askers' lists keep behind the row. `None` for an input row, or a row naming no entry
/// of its kind in `memo`. Makes and keeps the entry's flat list, as any ask of it does. The
/// copy is in `alloc`.
pub fn flat_reads_behind<A: Allocator>(memo: &crate::Memo, row: crate::Read, alloc: A) -> Option<Vec<crate::Read, A>> {
    let crate::Read::Query { kind, key } = row else { return None };
    let slot = if key.is_spill() { Some(memo.spill()) } else { memo.try_slot(key.arena()) }?;
    let head = slot.local(key.local())?;
    if !ptr::eq(head.kind, kind.kind()) {
        return None;
    }
    let mut out = Vec::new_in(alloc);
    out.extend_from_slice(crate::record::flat_of(memo, head));
    Some(out)
}
