/// Compile and run a Rust cell via `blaze run <cell.rs>` with a bounded 30s timeout.
pub fn eval_rust_cell<'a>(
    prior_cells: &[&str],
    code: &str,
    input_json: &str,
    cwd: &str,
    path_env: Option<&str>,
    alloc: Alloc<'a>,
) -> RustEvalResult<'a> {
    let Some(blaze_bin) = find_blaze_binary(path_env) else {
        return RustEvalResult {
            ok: false,
            output_json: None,
            stdout: AString::new_in(alloc),
            stderr: AString::from_str_in(
                "blaze binary not found on PATH (set BLAZE_BIN or install `blaze`); blaze-shell never falls back to rustc or cargo",
                alloc,
            ),
            compile_ms: 0,
            run_ms: 0,
        };
    };

    let source = synthesize_cell_source(prior_cells, code, input_json);
    let hash = blaze_own::xxhash64_slice(source.as_bytes(), 0x424c_415a_4553_4831);
    let cell_dir = std::env::temp_dir().join("blaze-shell-cells");
    if let Err(e) = fs::create_dir_all(&cell_dir) {
        let msg = format!("failed to create rust cell cache dir {}: {e}", cell_dir.display());
        return RustEvalResult {
            ok: false,
            output_json: None,
            stdout: AString::new_in(alloc),
            stderr: AString::from_str_in(&msg, alloc),
            compile_ms: 0,
            run_ms: 0,
        };
    }
    let script_path = cell_dir.join(format!("cell-{hash:016x}.rs"));
    if let Err(e) = fs::write(&script_path, &source) {
        let msg = format!("failed to write rust cell {}: {e}", script_path.display());
        return RustEvalResult {
            ok: false,
            output_json: None,
            stdout: AString::new_in(alloc),
            stderr: AString::from_str_in(&msg, alloc),
            compile_ms: 0,
            run_ms: 0,
        };
    }

    let t0 = Instant::now();
    let mut child = match Command::new(&blaze_bin)
        .arg("run")
        .arg(&script_path)
        .current_dir(cwd)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
    {
        Ok(c) => c,
        Err(e) => {
            let msg = format!("failed to spawn `{} run {}`: {e}", blaze_bin.display(), script_path.display());
            return RustEvalResult {
                ok: false,
                output_json: None,
                stdout: AString::new_in(alloc),
                stderr: AString::from_str_in(&msg, alloc),
                compile_ms: 0,
                run_ms: 0,
            };
        }
    };

    let out_reader = child.stdout.take().map(|mut pipe| {
        thread::spawn(move || {
            let mut buf = Vec::new();
            let _ = std::io::Read::read_to_end(&mut pipe, &mut buf);
            buf
        })
    });
    let err_reader = child.stderr.take().map(|mut pipe| {
        thread::spawn(move || {
            let mut buf = Vec::new();
            let _ = std::io::Read::read_to_end(&mut pipe, &mut buf);
            buf
        })
    });

    let deadline = t0 + RUST_CELL_TIMEOUT;
    let status = loop {
        match child.try_wait() {
            Ok(Some(st)) => break Ok(st),
            Ok(None) => {
                if Instant::now() >= deadline {
                    let _ = child.kill();
                    let _ = child.wait();
                    break Err("rust cell timed out after 30s");
                }
                thread::sleep(Duration::from_millis(5));
            }
            Err(_) => {
                let _ = child.kill();
                break Err("failed waiting on blaze run child");
            }
        }
    };

    let elapsed_ms = t0.elapsed().as_millis() as u64;
    let raw_out = out_reader
        .and_then(|h| h.join().ok())
        .unwrap_or_default();
    let raw_err = err_reader
        .and_then(|h| h.join().ok())
        .unwrap_or_default();

    let status = match status {
        Ok(s) => s,
        Err(timeout_msg) => {
            return RustEvalResult {
                ok: false,
                output_json: None,
                stdout: AString::from_str_in(&String::from_utf8_lossy(&raw_out), alloc),
                stderr: AString::from_str_in(timeout_msg, alloc),
                compile_ms: elapsed_ms,
                run_ms: 0,
            };
        }
    };

    let stdout_full = String::from_utf8_lossy(&raw_out);
    let stderr_full = String::from_utf8_lossy(&raw_err);

    // Extract the final `__BLAZE_CELL_JSON__:` sentinel line from stdout.
    let mut user_stdout = String::new();
    let mut output_json: Option<AString<'a>> = None;
    for line in stdout_full.lines() {
        if let Some(json_part) = line.strip_prefix(CELL_JSON_SENTINEL) {
            output_json = Some(AString::from_str_in(json_part.trim(), alloc));
        } else {
            if !user_stdout.is_empty() {
                user_stdout.push('\n');
            }
            user_stdout.push_str(line);
        }
    }

    RustEvalResult {
        ok: status.success(),
        output_json,
        stdout: AString::from_str_in(&user_stdout, alloc),
        stderr: AString::from_str_in(stderr_full.trim_end(), alloc),
        compile_ms: elapsed_ms,
        run_ms: 0,
    }
}
