//! Live `rust { ... }` / `:rs ...` cell execution powered exclusively by `blaze run`
//! (NEVER `rustc` or `cargo` — rules 1 & 3).
//!
//! Synthesizes a self-contained zero-dependency `.rs` file under the cache directory that:
//! - Re-emits top-level item definitions (`fn`, `struct`, `enum`, `const`, `type`, `use`, `mod`,
//!   `trait`, `impl`) from `prior_cells` so earlier REPL cells stay in scope (and fork in O(1)
//!   with the shell's `EngineState::rust_cells`).
//! - Binds `input: &str` to the serialized `$in` JSON payload.
//! - Uses autoref specialization to serialize primitives, strings, and `Vec<T>` as structured
//!   JSON (`__BLAZE_CELL_JSON__:<json>`) while formatting arbitrary `Debug` structs cleanly as
//!   JSON strings — zero external crates required.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::thread;
use std::time::{Duration, Instant};

use blaze_own::{AString, Alloc};
use blaze_sh::RustEvalResult;

/// Sentinel prefix emitted on stdout by synthesized Rust cells carrying structured JSON output.
pub const CELL_JSON_SENTINEL: &str = "__BLAZE_CELL_JSON__:";

/// Bounded execution timeout for compiling + running a single Rust cell (rule 18 & 69).
const RUST_CELL_TIMEOUT: Duration = Duration::from_secs(30);

/// Locate the `blaze` executable (`BLAZE_BIN` env var first, then `PATH`).
/// Never falls back to `rustc` or `cargo` (rules 1 & 3).
pub fn find_blaze_binary(path_env: Option<&str>) -> Option<PathBuf> {
    if let Ok(explicit) = std::env::var("BLAZE_BIN")
        && !explicit.trim().is_empty()
    {
        let p = PathBuf::from(explicit.trim());
        if p.is_file() {
            return Some(p);
        }
    }
    let path_str = path_env
        .map(str::to_owned)
        .or_else(|| std::env::var("PATH").ok())
        .unwrap_or_default();
    for dir in std::env::split_paths(&path_str) {
        let candidate = dir.join("blaze");
        if is_executable_file(&candidate) {
            return Some(candidate);
        }
    }
    None
}

fn is_executable_file(path: &Path) -> bool {
    let Ok(meta) = fs::metadata(path) else {
        return false;
    };
    if !meta.is_file() {
        return false;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        meta.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        true
    }
}

/// True when a cell's source consists of top-level item definitions (`fn`, `struct`, `enum`,
/// `const`, `static`, `type`, `use`, `mod`, `trait`, `impl`) rather than an expression block.
pub fn looks_like_top_level_item(code: &str) -> bool {
    let trimmed = code.trim_start();
    let without_attrs = strip_leading_attributes(trimmed);
    const PREFIXES: &[&str] = &[
        "fn ", "pub fn ", "struct ", "pub struct ", "enum ", "pub enum ", "const ", "pub const ",
        "static ", "pub static ", "type ", "pub type ", "use ", "pub use ", "mod ", "pub mod ",
        "trait ", "pub trait ", "impl ", "impl<", "unsafe impl",
    ];
    PREFIXES.iter().any(|p| without_attrs.starts_with(p))
}

fn strip_leading_attributes(mut s: &str) -> &str {
    loop {
        s = s.trim_start();
        if let Some(rest) = s.strip_prefix("#[") {
            if let Some(end) = rest.find(']') {
                s = &rest[end + 1..];
                continue;
            }
        }
        if let Some(rest) = s.strip_prefix("//") {
            if let Some(nl) = rest.find('\n') {
                s = &rest[nl + 1..];
                continue;
            } else {
                return "";
            }
        }
        return s;
    }
}

