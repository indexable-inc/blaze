/// The ASCII text `ch` is confused with, if rustc's table has it.
pub(super) fn confusable(ch: char) -> Option<&'static str> {
    CONFUSABLES.binary_search_by_key(&ch, |&(c, _)| c).ok().map(|i| CONFUSABLES[i].1)
}

/// Whether rustc's table has `ch`.
pub(super) fn is_confusable(ch: char) -> bool {
    confusable(ch).is_some()
}
