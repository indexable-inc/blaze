/// Bytes from hex, at compile time.
pub const fn hex<const N: usize>(text: &str) -> [u8; N] {
    let text = text.as_bytes();
    assert!(text.len() == 2 * N, "hex of the wrong length");
    let mut out = [0u8; N];
    let mut i = 0;
    while i < N {
        out[i] = nibble(text[2 * i]) << 4 | nibble(text[2 * i + 1]);
        i += 1;
    }
    out
}

const fn nibble(c: u8) -> u8 {
    match c {
        b'0'..=b'9' => c - b'0',
        b'a'..=b'f' => c - b'a' + 10,
        _ => panic!("not a lowercase hex digit"),
    }
}

