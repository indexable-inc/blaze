pub struct Edge {
    pub name: &'static str,
    /// What the case is, and why the verdict is the right one for the reader.
    pub why: &'static str,
    pub key: [u8; 32],
    pub message: &'static [u8],
    pub signature: [u8; 64],
    pub want: Result<(), Refused>,
    /// Whether the cofactorless equation holds (None: a point does not decode).
    pub cofactorless: Option<bool>,
    /// Whether the cofactored equation, [8][S]B = [8]R + [8k]A, holds.
    pub cofactored: Option<bool>,
}

