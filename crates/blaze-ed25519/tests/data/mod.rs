//! The vectors the tests hold verification to, shared by the crate's tests (`#[path]` from
//! `src/tests.rs`) and `examples/cost.rs`. The including module has `Refused` and `Encoding` in
//! scope. The published vectors (the paper's 12 and Wycheproof's) are not here: they are
//! `published.txt`, read by `src/tests/published.rs` (README.md in this folder).
//!
//! Where every byte comes from:
//! - `RFC`: RFC 8032 section 7.1, all five Ed25519 vectors (TEST 1, 2, 3, 1024 and SHA(abc)),
//!   taken from the RFC's text. `edge.py` holds the RFC's secret keys and asserts that the public
//!   key and the signature it derives from each are the RFC's bytes.
//! - `EDGE`: generated by `edge.py` (the same Python reference): one case of each kind of
//!   signature that strict and lenient verifiers disagree on (a small-order or mixed-order key,
//!   a mixed-order or small-order R, S at or above L, a second encoding of R or of the key);
//!   the script prints each case with the verdicts of the cofactorless and cofactored
//!   equations. These are blaze's own cases, built for their kinds: the paper's numbered 12 are
//!   `published.txt`'s `speccheck` lines, verbatim.
//! - `TORSION`: the eight points of small order, [i]T for an order-8 T, from the same script.
//! - `MIXED_KEYS`: `PRIME_KEY` + `TORSION[i]` for i = 1..8 (orders 8L, 4L, 8L, 2L, 8L, 4L, 8L),
//!   from the same script.

