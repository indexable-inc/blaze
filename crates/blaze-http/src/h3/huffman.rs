/// Appends the decoding of `input` to `out`, or says why it is not a Huffman string: EOS inside
/// it, a code longer than 30 bits, or padding that is longer than 7 bits or not all ones
/// (RFC 7541, 5.2).
pub(crate) fn decode(input: &[u8], out: &mut Vec<u8>) -> Result<(), &'static str> {
    let mut code: u32 = 0;
    let mut len: usize = 0;
    for byte in input {
        for shift in (0..8).rev() {
            code = (code << 1) | u32::from((byte >> shift) & 1);
            len += 1;
            if len > 30 {
                return Err("a Huffman code is longer than 30 bits");
            }
            if let Ok(at) = BY_LEN[len].binary_search_by_key(&code, |&(it, _)| it) {
                let symbol = BY_LEN[len][at].1;
                if symbol == 256 {
                    return Err("a Huffman string holds EOS");
                }
                out.push(symbol as u8);
                code = 0;
                len = 0;
            }
        }
    }
    if len > 7 {
        return Err("a Huffman string's padding is longer than 7 bits");
    }
    if code != (1u32 << len) - 1 {
        return Err("a Huffman string's padding is not EOS's leading ones");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn encode(input: &[u8]) -> Vec<u8> {
        let (mut acc, mut bits, mut out) = (0u64, 0u32, Vec::new());
        for byte in input {
            let (code, len) = CODES[usize::from(*byte)];
            acc = (acc << len) | u64::from(code);
            bits += u32::from(len);
            while bits >= 8 {
                bits -= 8;
                out.push((acc >> bits) as u8);
            }
        }
        if bits > 0 {
            out.push(((acc << (8 - bits)) as u8) | (0xff >> bits));
        }
        out
    }

    /// RFC 7541, C.4.1 to C.4.3: request strings with Huffman.
    #[test]
    fn the_rfc_vectors_decode() {
        let cases: [(&[u8], &str); 3] = [
            (
                &[0xf1, 0xe3, 0xc2, 0xe5, 0xf2, 0x3a, 0x6b, 0xa0, 0xab, 0x90, 0xf4, 0xff],
                "www.example.com",
            ),
            (&[0xa8, 0xeb, 0x10, 0x64, 0x9c, 0xbf], "no-cache"),
            (&[0x25, 0xa8, 0x49, 0xe9, 0x5b, 0xa9, 0x7d, 0x7f], "custom-key"),
        ];
        for (bytes, text) in cases {
            let mut out = Vec::new();
            decode(bytes, &mut out).unwrap();
            assert_eq!(out, text.as_bytes());
            assert_eq!(encode(text.as_bytes()), bytes);
        }
    }

    #[test]
    fn every_byte_round_trips_and_the_table_is_prefix_free() {
        let all: Vec<u8> = (0..=255).collect();
        let mut out = Vec::new();
        decode(&encode(&all), &mut out).unwrap();
        assert_eq!(out, all);
        for (a, &(code_a, len_a)) in CODES.iter().enumerate() {
            for &(code_b, len_b) in &CODES[a + 1..] {
                let shorter = len_a.min(len_b);
                assert_ne!(
                    code_a >> (len_a - shorter),
                    code_b >> (len_b - shorter),
                    "a prefix of another code"
                );
            }
        }
    }

    #[test]
    fn bad_padding_and_eos_are_refused() {
        let mut out = Vec::new();
        // '0' is 00000; padded with zeros instead of ones.
        assert!(decode(&[0b0000_0000], &mut out).is_err());
        // Eight bits of ones past a whole symbol: padding longer than 7 bits.
        assert!(decode(&[0b0000_0111, 0xff], &mut out).is_err());
        // EOS, 30 ones, then padding.
        assert!(decode(&[0xff, 0xff, 0xff, 0xff], &mut out).is_err());
    }
}
