"""Writes `table/lang.rs`: rustc's language features, read from a rust checkout's
`compiler/rustc_feature/src/{unstable,accepted,removed}.rs` (MIT or Apache-2.0).

Input: `{"rust": "<rust checkout>", "out": "<path of lang.rs>"}` (inline, a path, or `-`).
"""

import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from typed_input import parse

SCRIPT = "table.py"

STRING = r'(?:r#".*?"#|"(?:[^"\\]|\\.)*")'
ENTRY = re.compile(
    r"\(\s*(unstable|incomplete|internal|accepted|removed)\s*,\s*(\w+)\s*,\s*\"([^\"]*)\"\s*,"
    r"\s*(None|Some\(\s*(\d+)\s*\))"
    r"(?:\s*,\s*(None|Some\(\s*(" + STRING + r")\s*\))(?:\s*,\s*(\d+))?)?\s*,?\s*\)",
    re.S,
)
KIND = {
    "unstable": "Unstable",
    "incomplete": "Incomplete",
    "internal": "Internal",
    "accepted": "Accepted",
    "removed": "Removed",
}


@dataclass(frozen=True)
class Input:
    rust: str
    out: str


@dataclass(frozen=True)
class Feature:
    name: str
    kind: str
    since: str
    issue: int | None
    reason: str | None
    pull: int | None


def without_comments(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))


def read(path: Path, kinds: set[str]) -> list[Feature]:
    text = without_comments(path.read_text())
    body = text[text.index("declare_features! (") :]
    features = []
    for m in ENTRY.finditer(body):
        kind, name, since, _, issue, _, reason, pull = m.groups()
        if kind not in kinds:
            sys.exit(f"{SCRIPT}: `{name}` in {path.name} is `{kind}`")
        features.append(
            Feature(name, KIND[kind], since, int(issue) if issue else None, reason, int(pull) if pull else None)
        )
    written = len(re.findall(r"\(\s*(?:" + "|".join(kinds) + r")\s*,", body))
    if written != len(features):
        sys.exit(f"{SCRIPT}: {path.name} has {written} entries, read {len(features)}")
    return features


def option(value: object) -> str:
    return "None" if value is None else f"Some({value})"


def render(features: list[Feature], declared: list[str], source: str) -> str:
    lines = [
        "//! rustc's language features: `compiler/rustc_feature/src/{unstable,accepted,removed}.rs` of",
        f"//! {source} (MIT or Apache-2.0), generated by `../table.py`; regenerate, don't edit.",
        "",
        "use super::Kind::{self, *};",
        "",
        "/// Every language feature: its name, what it is, the version it got there and its tracking",
        "/// issue, sorted by name.",
        "#[rustfmt::skip]",
        "pub(super) static LANG: &[(&str, Kind, &str, Option<u32>)] = &[",
    ]
    for f in features:
        lines.append(f'    ("{f.name}", {f.kind}, "{f.since}", {option(f.issue)}),')
    lines += [
        "];",
        "",
        "/// Each removed feature's reason and the pull request that removed it, sorted by name.",
        "#[rustfmt::skip]",
        "pub(super) static REMOVED: &[(&str, Option<&str>, Option<u32>)] = &[",
    ]
    for f in features:
        if f.kind == "Removed":
            lines.append(f'    ("{f.name}", {option(f.reason)}, {option(f.pull)}),')
    index = {f.name: i for i, f in enumerate(features)}
    lines += [
        "];",
        "",
        "/// The unstable features, as indexes into `LANG`, in the order `unstable.rs` declares them.",
        "#[rustfmt::skip]",
        "pub(super) static DECLARED: &[u16] = &[",
    ]
    for at in range(0, len(declared), 16):
        lines.append("    " + " ".join(f"{index[name]}," for name in declared[at : at + 16]))
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> None:
    match sys.argv[1:]:
        case [text]:
            config = parse(Input, text, SCRIPT)
        case _:
            print(f"usage: {SCRIPT} '{{\"rust\": \"<rust checkout>\", \"out\": \"<lang.rs>\"}}'", file=sys.stderr)
            sys.exit(2)
    src = Path(config.rust) / "compiler/rustc_feature/src"
    unstable = read(src / "unstable.rs", {"unstable", "incomplete", "internal"})
    declared = [f.name for f in unstable]
    features = (
        unstable
        + read(src / "accepted.rs", {"accepted"})
        + read(src / "removed.rs", {"removed"})
    )
    features.sort(key=lambda f: f.name)
    names = [f.name for f in features]
    if len(set(names)) != len(names):
        sys.exit(f"{SCRIPT}: a feature is declared twice")
    if len(features) > 1 << 16:
        sys.exit(f"{SCRIPT}: {len(features)} features do not fit a u16 index")
    commit = subprocess.run(
        ["git", "-C", config.rust, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    Path(config.out).write_text(render(features, declared, f"rust-lang/rust@{commit}"))


if __name__ == "__main__":
    main()
