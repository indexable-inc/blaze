//! rustc's explanations of its error codes, as `rustc --explain` gives them: the files of
//! `compiler/rustc_error_codes/src/error_codes/` at rust-lang/rust
//! ad3d0bc141a02cf446e384136d250a1f6950fed5, copied into `codes/` as they are, for the codes
//! `compiler/rustc_error_codes/src/lib.rs` lists (MIT or Apache-2.0, as rustc is; Copyright (c)
//! The Rust Project Contributors). A code rustc no longer emits keeps its file, which says so.

/// rustc's explanation of an error code (`rustc --explain`), for the JSON `explanation`
/// and for which codes the summary names.
pub fn explanation(code: &str) -> Option<&'static str> {
    let at = CODES.binary_search_by(|(it, _)| (*it).cmp(code)).ok()?;
    Some(CODES[at].1)
}

