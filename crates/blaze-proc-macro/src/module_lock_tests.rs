//! The module key's lock closure, read through blaze-manifest's one lock reader
//! ([`LockedPackages`] over `blaze_manifest::lock::Lock`), is byte-equal to the text reader it
//! replaced (`lock.split("[[package]]")`, 2026-11-21) on a well-formed lock: the modules on disk
//! (tempo's and turso's, keyed by the old reader) keep their keys.
//!
//! The old reader is kept HERE ONLY, as the control: [`old_closure`] is its text, verbatim but
//! for the error type. Nothing outside this file may split a lock by text (the ban test in
//! blaze-manifest, `lock_ban_tests.rs`, exempts this file by name).
//!
//! Prints `closures compared on tempo's lock: N equal (M refused alike)`.

