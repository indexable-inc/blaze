/// One package as the old text reader cut it out.
struct OldLocked<'l> {
    name: &'l str,
    version: &'l str,
    source: Option<&'l str>,
    checksum: Option<&'l str>,
    deps: Vec<&'l str>,
}

/// The old reader's loop, verbatim: what made a package named "" of a malformed entry.
fn old_read(lock: &str) -> Vec<OldLocked<'_>> {
    let mut packages = Vec::new();
    for entry in lock.split("[[package]]").skip(1) {
        let field = |key: &str| entry.lines().find_map(|line| line.trim().strip_prefix(key)).map(|it| it.trim().trim_matches('"'));
        let mut deps = Vec::new();
        if let Some(at) = entry.find("dependencies = [") {
            let list = &entry[at + "dependencies = [".len()..];
            let list = &list[..list.find(']').unwrap_or(list.len())];
            deps.extend(list.split(',').map(|it| it.trim().trim_matches('"')).filter(|it| !it.is_empty()));
        }
        packages.push(OldLocked {
            name: field("name = ").unwrap_or(""),
            version: field("version = ").unwrap_or(""),
            source: field("source = "),
            checksum: field("checksum = "),
            deps,
        });
    }
    packages
}

/// The old closure, verbatim but for its error (a [`ClosureError`] where it had one, the
/// dependency text where it named an unresolved one).
fn old_closure(lock: &str, name: &str, version: &str, corrections: &Table<std::alloc::Global>) -> Result<String, Result<ClosureError, String>> {
    let packages = old_read(lock);
    let root = packages
        .iter()
        .position(|it| it.name == name && it.version == version)
        .ok_or_else(|| Ok(ClosureError::NotLocked { name: name.to_owned(), version: version.to_owned() }))?;
    let mut seen = vec![false; packages.len()];
    seen[root] = true;
    let mut stack = vec![root];
    while let Some(at) = stack.pop() {
        for dep in &packages[at].deps {
            let mut parts = dep.splitn(3, ' ');
            let (dep_name, dep_version, dep_source) = (parts.next().unwrap_or(""), parts.next(), parts.next().map(|it| it.trim_matches(|c| c == '(' || c == ')')));
            let mut found = packages.iter().enumerate().filter(|(_, it)| {
                it.name == dep_name && dep_version.is_none_or(|v| it.version == v) && dep_source.is_none_or(|s| it.source == Some(s))
            });
            let (Some((index, _)), None) = (found.next(), found.next()) else {
                return Err(Err((*dep).to_owned()));
            };
            if !seen[index] {
                seen[index] = true;
                stack.push(index);
            }
        }
    }
    let mut lines = Vec::new();
    for (at, package) in packages.iter().enumerate() {
        if !seen[at] || at == root {
            continue;
        }
        let pin = package
            .checksum
            .or(package.source)
            .ok_or_else(|| Ok(ClosureError::Unpinned { name: package.name.to_owned(), version: package.version.to_owned() }))?;
        let pin = corrections.pin(package.name, package.version, pin);
        lines.push(format!("{} {} {pin}", package.name, package.version));
    }
    lines.sort();
    Ok(sha256_hex(lines.join("\n").as_bytes()))
}

/// Every package of `text` with the closure both readers give it: `(name version, old, new)`.
type Compared = Vec<(String, Result<String, Result<ClosureError, String>>, Result<String, ClosureError>)>;

fn compare(old_text: &str, new_text: &str) -> Compared {
    let table = Table::checked_in(std::alloc::Global);
    let lock = Lock::read(new_text.as_bytes(), blaze_own::testing::heap().alloc()).expect("tempo's lock excerpt reads");
    let locked = LockedPackages::of(&lock);
    let mut out = Vec::new();
    for package in lock.packages.iter() {
        let (name, version) = (package.name.as_str(), package.version.to_string());
        out.push((format!("{name} {version}"), old_closure(old_text, name, &version, &table), locked.closure(name, &version)));
    }
    out
}

/// Each closure of tempo's excerpt is the old reader's, byte for byte, refusals included: no
/// module key a well-formed lock gives can move.
#[test]
fn the_closure_is_the_old_readers_byte_for_byte_on_tempos_lock() {
    let compared = compare(TEMPO, TEMPO);
    assert_eq!(compared.len(), 15, "the scan saw every package of the excerpt");
    let (mut equal, mut refused) = (0, 0);
    for (package, old, new) in &compared {
        match (old, new) {
            (Ok(old), Ok(new)) => {
                assert_eq!(old, new, "{package}: the closure digest moved");
                equal += 1;
            }
            (Err(Ok(old)), Err(new)) => {
                assert_eq!(old, new, "{package}: refused otherwise");
                refused += 1;
            }
            (old, new) => panic!("{package}: the old reader gave {old:?}, the new {new:?}"),
        }
    }
    // The two path packages: `tempo-member`'s closure holds `tempo-macros-x`, unpinned; every
    // other package (the git one and the D58-corrected synstructure among them) is a digest.
    assert_eq!((equal, refused), (14, 1), "every package compared, one refused alike");
    println!("closures compared on tempo's lock: {equal} equal ({refused} refused alike)");
}

/// The comparison is sensitive (rule 23's control): the old reader over the lock with one
/// checksum changed (unicode-ident's, in every closure but its own and the git leaf's) differs
/// from the new reader over the true lock exactly where the closure holds it.
#[test]
fn control_a_changed_pin_is_seen_by_the_comparison() {
    let true_sum = "d245f478577f809a851594d02313b640fb437e0bb33866753cff937863096954";
    let planted = TEMPO.replace(true_sum, "e245f478577f809a851594d02313b640fb437e0bb33866753cff937863096954");
    assert_ne!(planted, TEMPO, "the plant changed the text");
    let compared = compare(&planted, TEMPO);
    let moved: Vec<&str> = compared.iter().filter(|(_, old, new)| matches!((old, new), (Ok(a), Ok(b)) if a != b)).map(|(p, _, _)| p.as_str()).collect();
    let kept: Vec<&str> = compared.iter().filter(|(_, old, new)| matches!((old, new), (Ok(a), Ok(b)) if a == b)).map(|(p, _, _)| p.as_str()).collect();
    assert_eq!(kept, ["evm2-jit-build 0.1.0", "unicode-ident 1.0.26"], "only the closures without unicode-ident keep their digest");
    // 15 packages: two kept, `tempo-member` refused alike under both, the other twelve moved.
    assert_eq!(moved.len(), 12, "every closure holding unicode-ident moved: {moved:?}");
}

/// A malformed entry is the reader's typed refusal naming its line; the old reader (the twin)
/// made a package named "" of it, which a closure then walked.
#[test]
fn a_malformed_entry_is_refused_with_its_line_not_a_package_named_empty() {
    let text = "version = 4\n\n[[package]]\nname = \"m\"\nversion = \"1.0.0\"\n\n[[package]]\nversion = \"2.0.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n";
    match Lock::read(text.as_bytes(), blaze_own::testing::heap().alloc()) {
        Err(LockRefused::Bad { line, package, why, .. }) => assert_eq!((line, package.as_str(), why), (7, "", "has no `name`")),
        Err(other) => panic!("refused otherwise: {other}"),
        Ok(_) => panic!("a lock entry with no name read"),
    }
    let old = old_read(text);
    assert_eq!(old.len(), 2);
    assert_eq!((old[1].name, old[1].version), ("", "2.0.0"), "the twin: the old reader's package named \"\"");
}
