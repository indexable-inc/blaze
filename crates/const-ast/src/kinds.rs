//! The kinds the views read and a builder opens, numbered as `parser::SyntaxKind` numbers
//! them, with [`TOKEN`] set on a token's. Nothing outside this crate sees these numbers: they
//! shift when the grammar changes, and the views change with them. A macro names a node kind
//! by [`crate::Kind`]'s constant of the same name. `tests::kinds_are_the_grammars` checks every
//! one against `SyntaxKind`, and `tests::every_node_kind_is_public` that every node kind is
//! here and in `Kind`; `UPDATE_EXPECT=1` writes the numbers it finds.
//!
//! The tokens come first, then every node kind from `ABI` on in the grammar's order. The
//! grammar numbers eight contextual keywords after its nodes (`UNWRAP_BINDER_KW` ..
//! `UNIQ_KW`, to keep older kinds' numbers); they are tokens, so they are not here.

