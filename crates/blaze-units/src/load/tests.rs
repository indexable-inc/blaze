/// One database, with the standard library in its tree, that views are opened in. The graph's
/// tests (`graph/tests.rs`) open theirs here too.
pub(crate) struct Fixture {
    db: Database,
    tree: Arc<MemTree>,
    library: ContentId,
}

/// A view's build: its files (under `ws/` the workspace's, mounted at [`WS`]), its command
/// line, the variables past `HOME`, and the mounts past the workspace's and the library's.
pub(crate) struct Ask<'a> {
    pub(crate) files: &'a [(&'a str, &'a str)],
    pub(crate) command: Command,
    pub(crate) args: &'a [&'a str],
    pub(crate) env: &'a [(&'a str, &'a str)],
    pub(crate) mounts: Vec<Mount>,
}

pub(crate) fn ask<'a>(files: &'a [(&'a str, &'a str)]) -> Ask<'a> {
    Ask { files, command: Command::Build, args: &[], env: &[], mounts: Vec::new() }
}

fn mount(at: &str, under: &str) -> Mount {
    Mount { at: at.to_owned(), origin: Origin::View, under: under.to_owned() }
}

impl Fixture {
    pub(crate) fn new() -> Fixture {
        let tree = Arc::new(MemTree::default());
        let library = library(&tree);
        let mut db = Database::new(Config { tree: Some(tree.clone()), dir: None, tags: 0 });
        crate::query::register(&mut db);
        Fixture { db, tree, library }
    }

    pub(crate) fn open(&self, ask: &Ask<'_>) -> ViewId {
        let files: Vec<(&str, &[u8])> = ask.files.iter().map(|(path, text)| (*path, text.as_bytes())).collect();
        let mut env: Vec<(String, String)> = vec![("HOME".to_owned(), "/home/u".to_owned())];
        env.extend(ask.env.iter().map(|(name, value)| ((*name).to_owned(), (*value).to_owned())));
        env.sort();
        let mut mounts = vec![mount(WS, "ws"), library_mount(self.library, COMMIT)];
        mounts.extend(ask.mounts.iter().cloned());
        mounts.sort();
        let config = BuildConfig {
            invocation: Invocation {
                command: ask.command,
                args: ask.args.iter().map(|it| (*it).to_owned()).collect(),
                root: WS.to_owned(),
                cwd: WS.to_owned(),
                env,
                files: Vec::new(),
            },
            mounts,
            host: HOST.to_owned(),
            library: library_at(COMMIT),
            std: STD.to_owned(),
        };
        self.db.open_with(View { root: self.tree.root(&files) }, &config.encode())
    }

    pub(crate) fn plan(&self, view: ViewId) -> Planned {
        self.db.pin().get::<Plan>(view, &()).expect("planned").get()
    }

    /// Whether `Q` of `key` ran in `view`, rather than being verified or reused.
    fn ran<Q: Query>(&self, view: ViewId, key: &Q::Key) -> bool {
        self.db.why(view, &QueryKey { kind: Q::KIND, input: Q::input(key) }).is_some()
    }

    /// Every query the view's plan read, itself first, through the memos' edges.
    fn reached(&self) -> Vec<QueryKey> {
        let mut queue = vec![QueryKey { kind: Plan::KIND, input: Plan::input(&()) }];
        let mut seen = Vec::new();
        while let Some(key) = queue.pop() {
            if seen.contains(&key) {
                continue;
            }
            let Some(memo) = self.db.memo(&key) else { continue };
            seen.push(key);
            queue.extend(memo.edges.iter().map(|it| it.read));
        }
        seen
    }
}

fn ready(planned: Planned) -> Units {
    match planned {
        Planned::Ready(units) => units,
        Planned::Needs(fetches) => panic!("the load needs {fetches:?}"),
        Planned::Failed(error) => panic!("the load failed: {}", error.what),
    }
}

fn failed(planned: Planned) -> String {
    match planned {
        Planned::Failed(error) => error.what,
        other => panic!("not an error: {other:?}"),
    }
}

/// The user's units of the package called `name` (none of the standard library's).
fn units_of<'a>(units: &'a Units, name: &str) -> Vec<(usize, &'a Unit)> {
    let id = &units.packages.iter().find(|it| it.name == name).unwrap_or_else(|| panic!("no package {name}")).id;
    units.graph.units.iter().enumerate().filter(|(_, it)| &it.pkg_id == id && !it.is_std).collect()
}

fn lib_of<'a>(units: &'a Units, name: &str) -> (usize, &'a Unit, &'a UnitPlan) {
    let (at, unit) = units_of(units, name)
        .into_iter()
        .find(|(_, it)| it.target.is_lib() && it.mode == Mode::Build)
        .unwrap_or_else(|| panic!("no library unit of {name}"));
    (at, unit, &units.plans[at])
}

fn env_of<'a>(plan: &'a UnitPlan, name: &str) -> Option<&'a str> {
    plan.env.iter().find(|(it, _)| it == name).map(|(_, value)| value.as_str())
}

fn roots_named(units: &Units) -> Vec<String> {
    let mut names: Vec<String> = units
        .graph
        .roots
        .iter()
        .map(|at| {
            let unit = &units.graph.units[*at];
            format!("{} {}", unit.target.name, unit.target.kind.join(","))
        })
        .collect();
    names.sort();
    names
}

const A: &str = "[package]\nname = \"a\"\nversion = \"0.1.0\"\nedition = \"2024\"\n";

#[test]
fn one_package_plans_its_library_and_binary_with_the_standard_library() {
    let fixture = Fixture::new();
    let files = [("ws/Cargo.toml", A), ("ws/src/lib.rs", "pub fn f() {}\n"), ("ws/src/main.rs", "fn main() {}\n")];
    let units = ready(fixture.plan(fixture.open(&ask(&files))));
    assert_eq!(roots_named(&units), ["a bin", "a lib"]);
    assert_eq!(units.plans.len(), units.graph.units.len());
    assert_eq!(units.target_dir, "/home/u/ws/target");
    assert_eq!(units.build_dir, "/home/u/ws/target");
    assert_eq!(units.finished, "`dev` profile [unoptimized + debuginfo]");
    assert!(units.warnings.is_empty(), "{:?}", units.warnings);
    let lock = units.lock.as_ref().expect("a new lock file");
    assert_eq!(lock.path, "/home/u/ws/Cargo.lock");
    assert_eq!(lock.text, format!("{HEADER}\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\n"));

    let a = units.packages.iter().find(|it| it.name == "a").expect("a");
    assert_eq!(a.id, "path+file:///home/u/ws#a@0.1.0");
    assert_eq!(a.manifest_path, "/home/u/ws/Cargo.toml");
    assert_eq!(a.source.as_deref(), Some("(/home/u/ws)"));
    assert!(a.is_member);

    let (lib_at, lib, lib_plan) = lib_of(&units, "a");
    assert_eq!(lib.platform, None);
    assert_eq!(env_of(lib_plan, "CARGO_PKG_NAME"), Some("a"));
    assert_eq!(env_of(lib_plan, "CARGO_MANIFEST_DIR"), Some(WS));
    assert!(lib_plan.extra_filename.starts_with('-'), "{lib_plan:?}");
    let (bin_at, bin) = units_of(&units, "a").into_iter().find(|(_, it)| it.target.kind == ["bin"]).expect("a bin");
    assert!(units.plans[bin_at].outputs.iter().any(|it| it == "/home/u/ws/target/debug/a"), "{:?}", units.plans[bin_at]);
    assert!(bin.dependencies.iter().any(|it| it.index == lib_at && it.extern_crate_name == "a"));

    // cargo's `attach_std_deps`: every unit but a build script's run gets each of the
    // library's roots, as `noprelude`, `public` and `nounused`.
    let std_deps: Vec<_> = bin.dependencies.iter().filter(|it| units.graph.units[it.index].is_std).collect();
    let names: Vec<&str> = std_deps.iter().map(|it| it.extern_crate_name.as_str()).collect();
    assert_eq!(names, ["alloc", "compiler_builtins", "core", "panic_unwind", "proc_macro", "std"]);
    assert!(std_deps.iter().all(|it| (it.public, it.noprelude, it.nounused) == (Some(true), Some(true), Some(true))));
    let std_platforms: Vec<_> = units.graph.units.iter().filter(|it| it.is_std).map(|it| (&it.target.name, it.mode, &it.platform)).collect();
    assert!(std_platforms.iter().all(|(_, _, it)| it.is_none()), "{std_platforms:?}");

    // compiler_builtins' build script has no `-C extra-filename` (cargo's new build-dir
    // layout), yet its plan names its unit id, which its run's and its library's hashes take.
    let script_at = units
        .graph
        .units
        .iter()
        .position(|it| it.is_std && it.target.is_custom_build() && it.mode == Mode::Build)
        .expect("compiler_builtins' build script");
    let script = &units.plans[script_at];
    assert_eq!(script.extra_filename, "", "{script:?}");
    assert_eq!(script.unit_id.len(), 16, "{script:?}");
    for plan in &units.plans {
        assert!(plan.extra_filename.is_empty() || plan.extra_filename == format!("-{}", plan.unit_id), "{plan:?}");
    }
}

#[test]
fn doc_checks_the_targets_cargo_doc_documents() {
    let fixture = Fixture::new();
    let files = [
        ("ws/Cargo.toml", A),
        ("ws/src/lib.rs", "pub fn f() {}\n"),
        ("ws/src/main.rs", "fn main() {}\n"),
        ("ws/src/bin/tool.rs", "fn main() {}\n"),
        ("ws/examples/e.rs", "fn main() {}\n"),
    ];
    let doc = Ask { command: Command::Doc, args: &["--no-deps", "--open"], ..ask(&files) };
    let units = ready(fixture.plan(fixture.open(&doc)));
    // cargo's `filter_default_targets`: a binary named as its package's library is left out.
    assert_eq!(roots_named(&units), ["a lib", "tool bin"]);
    let roots = units.graph.roots.iter().map(|&at| &units.graph.units[at]);
    assert!(roots.into_iter().all(|it| it.mode == Mode::Check), "every root is checked, none built");
    assert_eq!(units.finished, "`dev` profile [unoptimized + debuginfo]");

    let examples = Ask { command: Command::Doc, args: &["--examples"], ..ask(&files) };
    let units = ready(fixture.plan(fixture.open(&examples)));
    assert_eq!(roots_named(&units), ["e example"]);

    // What cargo doc would read and blaze doc does not honor yet stops the load, named.
    let flagged = Ask { command: Command::Doc, args: &[], env: &[("RUSTDOCFLAGS", "--html-in-header x.html")], ..ask(&files) };
    let what = failed(fixture.plan(fixture.open(&flagged)));
    assert!(what.contains("rustdoc's flags") && what.contains("`--html-in-header x.html`"), "{what}");
    let browser = [("CARGO_DOC_BROWSER", "firefox")];
    let opened = Ask { command: Command::Doc, args: &["--open"], env: &browser, ..ask(&files) };
    let what = failed(fixture.plan(fixture.open(&opened)));
    assert!(what.contains("`doc.browser` (`CARGO_DOC_BROWSER`)"), "{what}");
    let unopened = Ask { command: Command::Doc, args: &[], env: &browser, ..ask(&files) };
    ready(fixture.plan(fixture.open(&unopened)));
}

