//! `Cargo.lock`, read and written as cargo 1.99.0 (5f94df4789) does: the schema of
//! `cargo-util-schemas`' `lockfile.rs`, the decoding and encoding of `src/resolver/encode.rs`
//! and the bytes of `src/ops/lockfile.rs`.
//!
//! Values are written with the `toml` crate cargo 1.99.0 uses (1.1.2), whose quoting and
//! escaping of strings is part of the bytes.

use std::cmp::Ordering;
use std::fmt;
use std::path::Path;
use std::str::FromStr;

use anyhow::{Context as _, Result, anyhow, bail};
use blaze_hash::{HashMap, HashSet};
use serde::{Deserialize, de};
use url::Url;

use crate::graph::Graph;
use crate::interning::InternedString;
