//! `Cargo.lock`, read and written as cargo 1.99.0 (5f94df4789) does: the schema of
//! `cargo-util-schemas`' `lockfile.rs`, the decoding and encoding of `src/resolver/encode.rs`
//! and the bytes of `src/ops/lockfile.rs`.
//!
//! The text is read with blaze-toml, by hand into the schema's types: an error names the
//! file, the key path (`package[3].version`) and the line, and keys the schema does not know
//! are ignored, as cargo ignores them. Strings are written as the `toml` crate cargo 1.99.0
//! uses (1.1.2) writes them, whose choice of quoting is part of the bytes.

