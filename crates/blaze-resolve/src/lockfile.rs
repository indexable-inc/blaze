type Result<T, E = ResolveError> = std::result::Result<T, E>;

pub const LOCKFILE_NAME: &str = "Cargo.lock";

const MARKER_LINE: &str = "# This file is automatically @generated by Cargo.";
const EXTRA_LINE: &str = "# It is not intended for manual editing.";

/// A `Cargo.lock` as written, before its entries are matched to packages.
#[derive(Debug)]
pub struct TomlLockfile {
    /// Absent in the encodings before 3.
    pub version: Option<u32>,
    pub package: Option<Vec<TomlLockfileDependency>>,
    /// The root package of the oldest lock files, which list it apart.
    pub root: Option<TomlLockfileDependency>,
    pub metadata: Option<LockfileMetadata>,
    pub patch: TomlLockfilePatch,
}

#[derive(Debug, Default)]
pub struct TomlLockfilePatch {
    pub unused: Vec<TomlLockfileDependency>,
}

/// A `[[package]]` (or `[[patch.unused]]`) entry.
#[derive(Debug, PartialOrd, Ord, PartialEq, Eq)]
pub struct TomlLockfileDependency {
    pub name: String,
    pub version: String,
    /// None for a path package.
    pub source: Option<TomlLockfileSourceId>,
    pub checksum: Option<String>,
    pub dependencies: Option<Vec<TomlLockfilePackageId>>,
    pub replace: Option<TomlLockfilePackageId>,
}

/// A `source = "..."` as written, with its kind and URL to order by.
#[derive(Debug, Clone)]
pub struct TomlLockfileSourceId {
    source_str: String,
    kind: SourceKind,
    url: Url,
}

impl TomlLockfileSourceId {
    pub fn new(source: String) -> Result<Self, SourceError> {
        let Some((kind, url)) = source.split_once('+') else {
            return Err(SourceError::NoKind { source });
        };
        // A sparse URL keeps its `sparse+`.
        let url = Url::parse(if kind == "sparse" { &source } else { url })
            .map_err(|error| SourceError::InvalidUrl { url: url.to_owned(), error })?;
        let kind = match kind {
            "git" => SourceKind::Git(GitReference::from_query(url.query_pairs())),
            "registry" => SourceKind::Registry,
            "sparse" => SourceKind::SparseRegistry,
            "path" => SourceKind::Path,
            kind => {
                let kind = kind.to_owned();
                return Err(SourceError::UnsupportedProtocol { kind, source });
            }
        };
        Ok(TomlLockfileSourceId { source_str: source, kind, url })
    }

    pub fn kind(&self) -> &SourceKind {
        &self.kind
    }

    pub fn url(&self) -> &Url {
        &self.url
    }

    pub fn source_str(&self) -> &str {
        &self.source_str
    }
}

impl std::hash::Hash for TomlLockfileSourceId {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.kind.hash(state);
        self.url.hash(state);
    }
}

impl PartialEq for TomlLockfileSourceId {
    fn eq(&self, other: &Self) -> bool {
        self.kind == other.kind && self.url == other.url
    }
}

impl Eq for TomlLockfileSourceId {}

impl PartialOrd for TomlLockfileSourceId {
    fn partial_cmp(&self, other: &TomlLockfileSourceId) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for TomlLockfileSourceId {
    fn cmp(&self, other: &TomlLockfileSourceId) -> Ordering {
        self.kind.cmp(&other.kind).then_with(|| self.url.cmp(&other.url))
    }
}

/// An entry of `dependencies = [...]`: `name`, `name version` or `name version (source)`,
/// with only as much as tells the packages of the lock file apart (from encoding 2).
#[derive(Debug, PartialOrd, Ord, PartialEq, Eq, Hash, Clone)]
pub struct TomlLockfilePackageId {
    pub name: String,
    pub version: Option<String>,
    pub source: Option<TomlLockfileSourceId>,
}

impl fmt::Display for TomlLockfilePackageId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.name)?;
        if let Some(s) = &self.version {
            write!(f, " {}", s)?;
        }
        if let Some(s) = &self.source {
            write!(f, " ({})", s.source_str)?;
        }
        Ok(())
    }
}

/// Why a written package id could not be read: its form, or its source.
enum PackageIdWhy {
    /// A third part not in parentheses.
    Form,
    Source(SourceError),
}

impl TomlLockfilePackageId {
    /// `name`, `name version` or `name version (source)`.
    fn read(s: &str) -> Result<TomlLockfilePackageId, PackageIdWhy> {
        let mut s = s.splitn(3, ' ');
        let name = s.next().unwrap_or_else(|| unreachable!("`splitn` yields a first part"));
        let version = s.next();
        let source = match s.next() {
            Some(s) => match s.strip_prefix('(').and_then(|s| s.strip_suffix(')')) {
                Some(s) => {
                    Some(TomlLockfileSourceId::new(s.to_owned()).map_err(PackageIdWhy::Source)?)
                }
                None => return Err(PackageIdWhy::Form),
            },
            None => None,
        };
        Ok(TomlLockfilePackageId {
            name: name.to_owned(),
            version: version.map(|v| v.to_owned()),
            source,
        })
    }
}

impl FromStr for TomlLockfilePackageId {
    type Err = ResolveError;

    fn from_str(s: &str) -> Result<TomlLockfilePackageId> {
        TomlLockfilePackageId::read(s).map_err(|why| match why {
            PackageIdWhy::Form => ResolveError::SerializedPackageId { text: s.to_owned() },
            PackageIdWhy::Source(error) => ResolveError::Source(error),
        })
    }
}

type Item<'d, 't> = blaze_toml::Item<'d, 't, Global>;

/// Where in the lock file a value is, as a key path: `package[3].dependencies[0]`.
#[derive(Clone, Copy)]
struct At<'a> {
    table: &'static str,
    index: Option<usize>,
    field: Option<&'a str>,
    element: Option<usize>,
}

impl<'a> At<'a> {
    const fn top(table: &'static str) -> At<'a> {
        At { table, index: None, field: None, element: None }
    }

    fn index(self, index: usize) -> At<'a> {
        At { index: Some(index), ..self }
    }

    fn field(self, field: &'a str) -> At<'a> {
        At { field: Some(field), ..self }
    }

    fn element(self, element: usize) -> At<'a> {
        At { element: Some(element), ..self }
    }

    fn wrong(self, item: Item<'_, '_>, expected: &'static str) -> ResolveError {
        let (key, line) = (self.to_string(), item.line_col().0);
        ResolveError::LockfileType { key, line, expected, found: item.kind().name() }
    }

    fn table<'d, 't>(self, item: Item<'d, 't>) -> Result<Item<'d, 't>> {
        match item.is_table() {
            true => Ok(item),
            false => Err(self.wrong(item, "a table")),
        }
    }

    fn array<'d, 't>(self, item: Item<'d, 't>) -> Result<Item<'d, 't>> {
        match item.is_array() {
            true => Ok(item),
            false => Err(self.wrong(item, "an array")),
        }
    }

    fn string<'d>(self, item: Item<'d, '_>) -> Result<&'d str> {
        item.as_str().ok_or_else(|| self.wrong(item, "a string"))
    }

    /// The field `self.field` of `table`, which must be there.
    fn required<'d, 't>(self, table: Item<'d, 't>, field: &'a str) -> Result<Item<'d, 't>> {
        let at = self.field(field);
        table.get(field).ok_or_else(|| ResolveError::LockfileMissing {
            key: at.to_string(),
            line: table.line_col().0,
        })
    }

    fn source(self, item: Item<'_, '_>) -> Result<TomlLockfileSourceId> {
        let text = self.string(item)?;
        TomlLockfileSourceId::new(text.to_owned()).map_err(|error| ResolveError::LockfileSource {
            key: self.to_string(),
            line: item.line_col().0,
            error,
        })
    }

    fn package_id(self, item: Item<'_, '_>) -> Result<TomlLockfilePackageId> {
        let text = self.string(item)?;
        TomlLockfilePackageId::read(text).map_err(|why| {
            let (key, line) = (self.to_string(), item.line_col().0);
            match why {
                PackageIdWhy::Form => {
                    ResolveError::LockfilePackageId { key, line, text: text.to_owned() }
                }
                PackageIdWhy::Source(error) => ResolveError::LockfileSource { key, line, error },
            }
        })
    }
}

impl fmt::Display for At<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.table)?;
        if let Some(index) = self.index {
            write!(f, "[{index}]")?;
        }
        if let Some(field) = self.field {
            write!(f, ".{field}")?;
        }
        if let Some(element) = self.element {
            write!(f, "[{element}]")?;
        }
        Ok(())
    }
}

/// A `[[package]]`, `[root]` or `[[patch.unused]]` table.
fn read_dependency(at: At<'_>, item: Item<'_, '_>) -> Result<TomlLockfileDependency> {
    let table = at.table(item)?;
    let name = at.field("name").string(at.required(table, "name")?)?.to_owned();
    let version = at.field("version").string(at.required(table, "version")?)?.to_owned();
    let source = match table.get("source") {
        Some(item) => Some(at.field("source").source(item)?),
        None => None,
    };
    let checksum = match table.get("checksum") {
        Some(item) => Some(at.field("checksum").string(item)?.to_owned()),
        None => None,
    };
    let dependencies = match table.get("dependencies") {
        Some(item) => {
            let at = at.field("dependencies");
            let array = at.array(item)?;
            let mut dependencies = Vec::with_capacity(array.len());
            for (i, item) in array.children().enumerate() {
                dependencies.push(at.element(i).package_id(item)?);
            }
            Some(dependencies)
        }
        None => None,
    };
    let replace = match table.get("replace") {
        Some(item) => Some(at.field("replace").package_id(item)?),
        None => None,
    };
    Ok(TomlLockfileDependency { name, version, source, checksum, dependencies, replace })
}

/// An array of `[[...]]` tables.
fn read_dependencies(at: At<'_>, item: Item<'_, '_>) -> Result<Vec<TomlLockfileDependency>> {
    let array = at.array(item)?;
    let mut entries = Vec::with_capacity(array.len());
    for (i, item) in array.children().enumerate() {
        entries.push(read_dependency(at.index(i), item)?);
    }
    Ok(entries)
}

/// Parses the TOML of a lock file.
pub fn parse(text: &str) -> Result<TomlLockfile> {
    let doc = Document::parse_in(text, Limits::CARGO, Global).map_err(|error| {
        let (line, column) = error.line_col(text);
        ResolveError::LockfileToml { error, line, column }
    })?;
    let root = doc.root();
    let version = match root.get("version") {
        Some(item) => {
            let Some(n) = item.as_integer() else {
                return Err(At::top("version").wrong(item, "an integer"));
            };
            // A version past `u32` is one this reader does not know, as any other is.
            match u32::try_from(n) {
                Ok(n) => Some(n),
                Err(_) => return Err(ResolveError::LockfileFuture { version: n }),
            }
        }
        None => None,
    };
    let package = match root.get("package") {
        Some(item) => Some(read_dependencies(At::top("package"), item)?),
        None => None,
    };
    let root_package = match root.get("root") {
        Some(item) => Some(read_dependency(At::top("root"), item)?),
        None => None,
    };
    let metadata = match root.get("metadata") {
        Some(item) => {
            let at = At::top("metadata");
            let table = at.table(item)?;
            let mut metadata = LockfileMetadata::new();
            for item in table.children() {
                let value = at.field(item.key()).string(item)?;
                metadata.insert(item.key().to_owned(), value.to_owned());
            }
            Some(metadata)
        }
        None => None,
    };
    let patch = match root.get("patch") {
        Some(item) => {
            let at = At::top("patch");
            let table = at.table(item)?;
            let unused = at.required(table, "unused")?;
            TomlLockfilePatch { unused: read_dependencies(At::top("patch.unused"), unused)? }
        }
        None => TomlLockfilePatch::default(),
    };
    Ok(TomlLockfile { version, package, root: root_package, metadata, patch })
}

/// The path packages of the workspace, by name and version: what a lock file's entries
/// without a source are matched to. cargo collects the workspace members, the path
/// dependencies reachable from them, and those of the root `[patch]` and `[replace]`.
pub type PathDeps = Map<String, Map<Version, SourceId, FixedState, Global>, FixedState, Global>;

/// The packages and edges of a lock file. Its edges have no dependencies and it has no
/// features: it guides a resolve, it is not one. Entries without a source that match no path
/// package of `path_deps` are left out, as cargo leaves out a member that was removed.
/// `original` is the text the lock file was parsed from.
pub fn into_resolve(
    resolve: TomlLockfile,
    original: &str,
    path_deps: &PathDeps,
) -> Result<Resolve> {
    let mut checksums = Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None });

    let mut version = match resolve.version {
        Some(4) => ResolveVersion::V4,
        Some(3) => ResolveVersion::V3,
        Some(n) => return Err(ResolveError::LockfileFuture { version: n.into() }),
        // 1 or 2; 1 until something says 2.
        None => ResolveVersion::V1,
    };

    let packages = {
        let mut packages = resolve.package.unwrap_or_default();
        if let Some(root) = resolve.root {
            packages.insert(0, root);
        }
        packages
    };

    let get_source_id = |pkg: &TomlLockfileDependency| -> Option<SourceId> {
        let version_source = path_deps.get(&pkg.name)?;
        if version_source.len() == 1 {
            return version_source.values().next().copied();
        }
        // A version that does not parse matches no path package.
        let pkg_version = parse_version(&pkg.version).ok()?;
        version_source.get(&pkg_version).copied()
    };

    let live_pkgs = {
        let mut live_pkgs = Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None });
        let mut all_pkgs = Set::new(SetOpts { hasher: FixedState, alloc: Global, capacity: None });
        for pkg in packages.iter() {
            let enc_id = TomlLockfilePackageId {
                name: pkg.name.clone(),
                version: Some(pkg.version.clone()),
                source: pkg.source.clone(),
            };
            if !all_pkgs.insert(enc_id.clone()) {
                return Err(ResolveError::LockfileTwice { name: pkg.name.clone() });
            }
            let source = match &pkg.source {
                Some(source) => Some(SourceId::from_url(source.source_str())?),
                None => get_source_id(pkg),
            };
            let Some(source) = source else { continue };
            let id = PackageId::try_new(pkg.name.as_str(), &pkg.version, source)?;
            // A checksum on the package is encoding 2.
            if let Some(cksum) = &pkg.checksum {
                version = version.max(ResolveVersion::V2);
                checksums.insert(id, Some(cksum.clone()));
            }
            assert!(live_pkgs.insert(enc_id, (id, pkg)).is_none())
        }
        live_pkgs
    };

    // name -> version -> source -> id, to find the ids of edges written briefly.
    let mut map: Map<&str, Map<String, Map<SourceId, PackageId, FixedState, Global>, FixedState, Global>, FixedState, Global> = Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None });
    for (id, _) in live_pkgs.values() {
        map.entry(id.name().as_str())
            .or_default()
            .entry(id.version().to_string())
            .or_default()
            .insert(id.source_id(), *id);
    }

    let mut lookup_id = |enc_id: &TomlLockfilePackageId| -> Option<PackageId> {
        let by_version = map.get(enc_id.name.as_str())?;
        let by_source = match &enc_id.version {
            Some(version) => by_version.get(version)?,
            None => {
                version = version.max(ResolveVersion::V2);
                if by_version.len() == 1 {
                    by_version.values().next().unwrap()
                } else {
                    return None;
                }
            }
        };
        match &enc_id.source {
            Some(source) => by_source.get(&SourceId::from_url(source.source_str()).ok()?).cloned(),
            None => {
                // A path package is never written with a source; otherwise a single
                // package of this name and version is encoding 2. Anything else is a bad merge
                // of the lock file, and is ignored.
                let mut path_packages = by_source.values().filter(|p| p.source_id().is_path());
                if let Some(path) = path_packages.next() {
                    if path_packages.next().is_some() {
                        return None;
                    }
                    Some(*path)
                } else if by_source.len() == 1 {
                    let id = by_source.values().next().unwrap();
                    version = version.max(ResolveVersion::V2);
                    Some(*id)
                } else {
                    None
                }
            }
        }
    };

    let mut g = Graph::new();
    for (id, _) in live_pkgs.values() {
        g.add(*id);
    }
    for &(ref id, pkg) in live_pkgs.values() {
        let Some(ref deps) = pkg.dependencies else { continue };
        for edge in deps.iter() {
            if let Some(to_depend_on) = lookup_id(edge) {
                g.link(*id, to_depend_on);
            }
        }
    }

    let replacements = {
        let mut replacements = Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None });
        for &(ref id, pkg) in live_pkgs.values() {
            if let Some(ref replace) = pkg.replace {
                assert!(pkg.dependencies.is_none());
                if let Some(replace_id) = lookup_id(replace) {
                    replacements.insert(*id, replace_id);
                }
            }
        }
        replacements
    };

    let mut metadata = resolve.metadata.unwrap_or_default();

    // Encoding 1 keeps the checksums in `[metadata]`.
    let prefix = "checksum ";
    let mut to_remove = Vec::new();
    for (k, v) in metadata.iter().filter(|p| p.0.starts_with(prefix)) {
        to_remove.push(k.to_owned());
        let k = k.strip_prefix(prefix).unwrap();
        let enc_id: TomlLockfilePackageId = k.parse().map_err(|cause| {
            ResolveError::LockfileChecksumKey { key: k.to_owned(), cause: Box::new(cause) }
        })?;
        let Some(id) = lookup_id(&enc_id) else { continue };
        let v = if v == "<none>" { None } else { Some(v.to_owned()) };
        checksums.insert(id, v);
    }
    // Checksums in `[metadata]` of an encoding 2 file are a bad merge: drop them all, to be
    // computed again.
    if !to_remove.is_empty() && version >= ResolveVersion::V2 {
        checksums.clear();
    }
    for k in to_remove {
        metadata.remove(&k);
    }

    let mut unused_patches = Vec::new();
    for pkg in resolve.patch.unused {
        let source = match &pkg.source {
            Some(source) => Some(SourceId::from_url(source.source_str())?),
            None => get_source_id(&pkg),
        };
        let Some(src) = source else { continue };
        unused_patches.push(PackageId::try_new(pkg.name.as_str(), &pkg.version, src)?);
    }

    // Encoding 1 sometimes ended in a blank line. A lock file of one package with one
    // newline at its end has nothing else to say it is encoding 2, which it then is.
    if original.ends_with('\n')
        && !original.ends_with("\n\n")
        && version == ResolveVersion::V1
        && g.iter().count() == 1
    {
        version = ResolveVersion::V2;
    }

    Ok(Resolve::new(
        g,
        replacements,
        Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None }),
        checksums,
        metadata,
        unused_patches,
        version,
        Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None }),
    ))
}

/// How many packages of a name and version the resolve has, which decides how briefly an
/// edge can be written.
pub(crate) struct EncodeState<'a> {
    counts: Option<Map<InternedString, Map<&'a Version, usize, FixedState, Global>, FixedState, Global>>,
}

impl<'a> EncodeState<'a> {
    pub(crate) fn new(resolve: &'a Resolve) -> EncodeState<'a> {
        let counts = (resolve.version() >= ResolveVersion::V2).then(|| {
            let mut map: Map<_, Map<_, usize, FixedState, Global>, FixedState, Global> = Map::new(MapOpts { hasher: FixedState, alloc: Global, capacity: None });
            for id in resolve.iter() {
                *map.entry(id.name()).or_default().entry(id.version()).or_insert(0) += 1;
            }
            map
        });
        EncodeState { counts }
    }
}

struct EncodedPackage {
    name: String,
    version: String,
    source: Option<TomlLockfileSourceId>,
    checksum: Option<String>,
    dependencies: Option<Vec<TomlLockfilePackageId>>,
    replace: Option<TomlLockfilePackageId>,
}

fn encodable_resolve_node(
    id: PackageId,
    resolve: &Resolve,
    state: &EncodeState<'_>,
) -> EncodedPackage {
    let (replace, deps) = match resolve.replacement(id) {
        Some(id) => (Some(encodable_package_id(id, state, resolve.version())), None),
        None => {
            let mut deps = resolve
                .deps_not_replaced(id)
                .map(|(id, _)| encodable_package_id(id, state, resolve.version()))
                .collect::<Vec<_>>();
            deps.sort();
            (None, Some(deps))
        }
    };
    EncodedPackage {
        name: id.name().to_string(),
        version: id.version().to_string(),
        source: encodable_source_id(id.source_id(), resolve.version()),
        dependencies: deps,
        replace,
        checksum: if resolve.version() >= ResolveVersion::V2 {
            resolve.checksums().get(&id).and_then(|s| s.clone())
        } else {
            None
        },
    }
}

pub(crate) fn encodable_package_id(
    id: PackageId,
    state: &EncodeState<'_>,
    resolve_version: ResolveVersion,
) -> TomlLockfilePackageId {
    let mut version = Some(id.version().to_string());
    let mut id_to_encode = id.source_id();
    // Before encoding 3 an edge to `branch = "master"` was written as one to the default
    // branch.
    if resolve_version <= ResolveVersion::V2
        && let Some(GitReference::Branch(b)) = id_to_encode.git_reference()
        && b == "master"
    {
        id_to_encode = SourceId::for_git(id_to_encode.url(), GitReference::DefaultBranch).unwrap();
    }
    let mut source = encodable_source_id(id_to_encode.without_precise(), resolve_version);
    if let Some(counts) = &state.counts {
        let version_counts = &counts[&id.name()];
        if version_counts[&id.version()] == 1 {
            source = None;
            if version_counts.len() == 1 {
                version = None;
            }
        }
    }
    TomlLockfilePackageId { name: id.name().to_string(), version, source }
}

fn encodable_source_id(id: SourceId, version: ResolveVersion) -> Option<TomlLockfileSourceId> {
    if id.is_path() {
        return None;
    }
    let url = if version >= ResolveVersion::V4 {
        id.as_encoded_url().to_string()
    } else {
        id.as_url().to_string()
    };
    Some(TomlLockfileSourceId::new(url).expect("source ID should have valid URLs"))
}

/// `text` as a TOML string value, spelled as cargo spells it (blaze-toml's writer).
fn push_value(text: &str, out: &mut String) {
    let mut spelled = blaze_own::String::new_in(Global);
    blaze_toml::write_string(text, &mut spelled);
    out.push_str(spelled.as_str());
}

/// `key = "value"` and a newline, both spelled as cargo spells them (blaze-toml's writer).
fn push_line(key: &str, value: &str, out: &mut String) {
    let mut spelled = blaze_own::String::new_in(Global);
    blaze_toml::write_key(key, &mut spelled);
    spelled.push_str(" = ");
    blaze_toml::write_string(value, &mut spelled);
    out.push_str(spelled.as_str());
    out.push('\n');
}

fn emit_package(dep: &EncodedPackage, out: &mut String) {
    push_line("name", &dep.name, out);
    push_line("version", &dep.version, out);
    if let Some(source) = &dep.source {
        push_line("source", &source.source_str, out);
    }
    if let Some(checksum) = &dep.checksum {
        push_line("checksum", checksum, out);
    }
    if let Some(slice) = &dep.dependencies {
        if !slice.is_empty() {
            out.push_str("dependencies = [\n");
            for child in slice.iter() {
                out.push(' ');
                push_value(&child.to_string(), out);
                out.push_str(",\n");
            }
            out.push_str("]\n");
        }
        out.push('\n');
    } else if let Some(replace) = &dep.replace {
        out.push_str("replace = ");
        push_value(&replace.to_string(), out);
        out.push_str("\n\n");
    }
}

/// The text of the lock file of `resolve`, keeping the comments at the top of `orig` (the
/// lock file there was) after cargo's two.
pub fn serialize_resolve(resolve: &Resolve, orig: Option<&str>) -> String {
    let mut ids: Vec<_> = resolve.iter().collect();
    ids.sort();
    let state = EncodeState::new(resolve);
    let packages: Vec<_> =
        ids.iter().map(|&id| encodable_resolve_node(id, resolve, &state)).collect();

    let mut metadata = resolve.metadata().clone();
    if resolve.version() == ResolveVersion::V1 {
        for &id in ids.iter().filter(|id| !id.source_id().is_path()) {
            let checksum = match resolve.checksums()[&id] {
                Some(ref s) => &s[..],
                None => "<none>",
            };
            let id = encodable_package_id(id, &state, resolve.version());
            metadata.insert(format!("checksum {}", id), checksum.to_owned());
        }
    }

    let unused: Vec<_> = resolve
        .unused_patches()
        .iter()
        .map(|id| EncodedPackage {
            name: id.name().to_string(),
            version: id.version().to_string(),
            source: encodable_source_id(id.source_id(), resolve.version()),
            dependencies: None,
            replace: None,
            checksum: if resolve.version() >= ResolveVersion::V2 {
                resolve.checksums().get(id).and_then(|x| x.clone())
            } else {
                None
            },
        })
        .collect();

    let mut out = String::new();
    out.push_str(MARKER_LINE);
    out.push('\n');
    out.push_str(EXTRA_LINE);
    out.push('\n');
    if let Some(orig) = orig {
        let mut comments = orig.lines().take_while(|line| line.starts_with('#'));
        if let Some(first) = comments.next() {
            if first != MARKER_LINE {
                out.push_str(first);
                out.push('\n');
            }
            if let Some(second) = comments.next() {
                if second != EXTRA_LINE {
                    out.push_str(second);
                    out.push('\n');
                }
                for line in comments {
                    out.push_str(line);
                    out.push('\n');
                }
            }
        }
    }

    if let Some(version) = resolve.version().number() {
        out.push_str(&format!("version = {version}\n\n"));
    }

    for dep in &packages {
        out.push_str("[[package]]\n");
        emit_package(dep, &mut out);
    }

    for entry in &unused {
        out.push_str("[[patch.unused]]\n");
        emit_package(entry, &mut out);
        out.push('\n');
    }

    // As toml writes a table of one table of strings, in the map's (sorted) order.
    if !metadata.is_empty() {
        out.push_str("[metadata]\n");
        for (key, value) in &metadata {
            push_line(key, value, &mut out);
        }
    }

    // Encoding 1 could end in blank lines, and keeps them; the others end in one newline.
    if resolve.version() >= ResolveVersion::V2 {
        while out.ends_with("\n\n") {
            out.pop();
        }
    }
    out
}

/// The same lock file: the same lines, or with `path_deps` (the workspace's path packages, as
/// `--locked` compares) the same resolve read back from both, so a lock file differing only in
/// its encoding or its spacing is left alone.
pub fn are_equal_lockfiles(orig: &str, current: &str, path_deps: Option<&PathDeps>) -> bool {
    if orig.lines().eq(current.lines()) {
        return true;
    }
    let Some(path_deps) = path_deps else { return false };
    let same = || -> Result<bool> {
        let old = into_resolve(parse(orig)?, orig, path_deps)?;
        let new = into_resolve(parse(current)?, current, path_deps)?;
        Ok(old == new)
    };
    matches!(same(), Ok(true))
}

/// What a resolve changes of `Cargo.lock` (`orig`, the lock file there): `None` when it is
/// already the same, else the new text, raised to the encoding a new lock file of the
/// workspace would have (from its lowest `rust-version`) if it was older. `same_resolve` (the
/// workspace's path packages) compares the resolves read back from both texts, as `--locked`
/// does, so a lock file differing only in its encoding or spacing is the same; without it the
/// lines are compared, and such a file is written again. Never an error: whether the change
/// may be made is the caller's policy (blaze-units' `lock`).
pub fn lockfile_change(
    resolve: &mut Resolve,
    orig: Option<&str>,
    lowest_rust_version: Option<&RustVersion>,
    same_resolve: Option<&PathDeps>,
) -> Option<String> {
    let mut out = serialize_resolve(resolve, orig);
    if let Some(orig) = orig
        && are_equal_lockfiles(orig, &out, same_resolve)
    {
        return None;
    }
    if same_resolve.is_some() {
        return Some(out);
    }
    let default_version = ResolveVersion::with_rust_version(lowest_rust_version);
    if resolve.version() < default_version {
        resolve.set_version(default_version);
        out = serialize_resolve(resolve, orig);
    }
    Some(out)
}
