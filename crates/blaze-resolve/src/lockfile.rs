use crate::resolve::{LockfileMetadata, Resolve, ResolveVersion};
use crate::source_id::{GitReference, SourceId, SourceKind};
use crate::version::RustVersion;

pub const LOCKFILE_NAME: &str = "Cargo.lock";

const MARKER_LINE: &str = "# This file is automatically @generated by Cargo.";
const EXTRA_LINE: &str = "# It is not intended for manual editing.";

/// A `Cargo.lock` as written, before its entries are matched to packages.
#[derive(Deserialize, Debug)]
pub struct TomlLockfile {
    /// Absent in the encodings before 3.
    pub version: Option<u32>,
    pub package: Option<Vec<TomlLockfileDependency>>,
    /// The root package of the oldest lock files, which list it apart.
    pub root: Option<TomlLockfileDependency>,
    pub metadata: Option<LockfileMetadata>,
    #[serde(default)]
    pub patch: TomlLockfilePatch,
}

#[derive(Deserialize, Debug, Default)]
pub struct TomlLockfilePatch {
    pub unused: Vec<TomlLockfileDependency>,
}

/// A `[[package]]` (or `[[patch.unused]]`) entry.
#[derive(Deserialize, Debug, PartialOrd, Ord, PartialEq, Eq)]
pub struct TomlLockfileDependency {
    pub name: String,
    pub version: String,
    /// None for a path package.
    pub source: Option<TomlLockfileSourceId>,
    pub checksum: Option<String>,
    pub dependencies: Option<Vec<TomlLockfilePackageId>>,
    pub replace: Option<TomlLockfilePackageId>,
}

/// A `source = "..."` as written, with its kind and URL to order by.
#[derive(Debug, Clone)]
pub struct TomlLockfileSourceId {
    source_str: String,
    kind: SourceKind,
    url: Url,
}

impl TomlLockfileSourceId {
    pub fn new(source: String) -> Result<Self> {
        let (kind, url) =
            source.split_once('+').ok_or_else(|| anyhow!("invalid source `{}`", source))?;
        // A sparse URL keeps its `sparse+`.
        let url = Url::parse(if kind == "sparse" { &source } else { url })
            .map_err(|msg| anyhow!("invalid url `{}`: {}", url, msg))?;
        let kind = match kind {
            "git" => SourceKind::Git(GitReference::from_query(url.query_pairs())),
            "registry" => SourceKind::Registry,
            "sparse" => SourceKind::SparseRegistry,
            "path" => SourceKind::Path,
            kind => bail!("unsupported source protocol: {}", kind),
        };
        Ok(TomlLockfileSourceId { source_str: source, kind, url })
    }

    pub fn kind(&self) -> &SourceKind {
        &self.kind
    }

    pub fn url(&self) -> &Url {
        &self.url
    }

    pub fn source_str(&self) -> &str {
        &self.source_str
    }
}

impl<'de> Deserialize<'de> for TomlLockfileSourceId {
    fn deserialize<D: de::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let s = String::deserialize(d)?;
        TomlLockfileSourceId::new(s).map_err(de::Error::custom)
    }
}

impl std::hash::Hash for TomlLockfileSourceId {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.kind.hash(state);
        self.url.hash(state);
    }
}

impl PartialEq for TomlLockfileSourceId {
    fn eq(&self, other: &Self) -> bool {
        self.kind == other.kind && self.url == other.url
    }
}

impl Eq for TomlLockfileSourceId {}

impl PartialOrd for TomlLockfileSourceId {
    fn partial_cmp(&self, other: &TomlLockfileSourceId) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for TomlLockfileSourceId {
    fn cmp(&self, other: &TomlLockfileSourceId) -> Ordering {
        self.kind.cmp(&other.kind).then_with(|| self.url.cmp(&other.url))
    }
}

/// An entry of `dependencies = [...]`: `name`, `name version` or `name version (source)`,
/// with only as much as tells the packages of the lock file apart (from encoding 2).
#[derive(Debug, PartialOrd, Ord, PartialEq, Eq, Hash, Clone)]
pub struct TomlLockfilePackageId {
    pub name: String,
    pub version: Option<String>,
    pub source: Option<TomlLockfileSourceId>,
}

impl fmt::Display for TomlLockfilePackageId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.name)?;
        if let Some(s) = &self.version {
            write!(f, " {}", s)?;
        }
        if let Some(s) = &self.source {
            write!(f, " ({})", s.source_str)?;
        }
        Ok(())
    }
}

impl FromStr for TomlLockfilePackageId {
    type Err = anyhow::Error;

    fn from_str(s: &str) -> Result<TomlLockfilePackageId> {
        let mut s = s.splitn(3, ' ');
        let name = s.next().unwrap();
        let version = s.next();
        let source = match s.next() {
            Some(s) => match s.strip_prefix('(').and_then(|s| s.strip_suffix(')')) {
                Some(s) => Some(TomlLockfileSourceId::new(s.to_owned())?),
                None => bail!("invalid serialied PackageId"),
            },
            None => None,
        };
        Ok(TomlLockfilePackageId {
            name: name.to_owned(),
            version: version.map(|v| v.to_owned()),
            source,
        })
    }
}

impl<'de> Deserialize<'de> for TomlLockfilePackageId {
    fn deserialize<D: de::Deserializer<'de>>(d: D) -> Result<TomlLockfilePackageId, D::Error> {
        String::deserialize(d)
            .and_then(|string| string.parse::<TomlLockfilePackageId>().map_err(de::Error::custom))
    }
}

/// Parses the TOML of a lock file.
pub fn parse(text: &str) -> Result<TomlLockfile> {
    Ok(toml::from_str(text)?)
}

/// The path packages of the workspace, by name and version: what a lock file's entries
/// without a source are matched to. cargo collects the workspace members, the path
/// dependencies reachable from them, and those of the root `[patch]` and `[replace]`.
pub type PathDeps = HashMap<String, HashMap<semver::Version, SourceId>>;

/// The packages and edges of a lock file. Its edges have no dependencies and it has no
/// features: it guides a resolve, it is not one. Entries without a source that match no path
/// package of `path_deps` are left out, as cargo leaves out a member that was removed.
/// `original` is the text the lock file was parsed from.
pub fn into_resolve(
    resolve: TomlLockfile,
    original: &str,
    path_deps: &PathDeps,
) -> Result<Resolve> {
    let mut checksums = HashMap::default();

    let mut version = match resolve.version {
        Some(4) => ResolveVersion::V4,
        Some(3) => ResolveVersion::V3,
        Some(n) => bail!(
            "lock file version `{}` was found, but this version of Cargo \
             does not understand this lock file, perhaps Cargo needs \
             to be updated?",
            n,
        ),
        // 1 or 2; 1 until something says 2.
        None => ResolveVersion::V1,
    };

    let packages = {
        let mut packages = resolve.package.unwrap_or_default();
        if let Some(root) = resolve.root {
            packages.insert(0, root);
        }
        packages
    };

    let get_source_id = |pkg: &TomlLockfileDependency| -> Option<SourceId> {
        let version_source = path_deps.get(&pkg.name)?;
        if version_source.len() == 1 {
            return version_source.values().next().copied();
        }
        let pkg_version = pkg.version.parse::<semver::Version>().ok()?;
        version_source.get(&pkg_version).copied()
    };

    let live_pkgs = {
        let mut live_pkgs = HashMap::default();
        let mut all_pkgs = HashSet::default();
        for pkg in packages.iter() {
            let enc_id = TomlLockfilePackageId {
                name: pkg.name.clone(),
                version: Some(pkg.version.clone()),
                source: pkg.source.clone(),
            };
            if !all_pkgs.insert(enc_id.clone()) {
                bail!("package `{}` is specified twice in the lockfile", pkg.name);
            }
            let source = match &pkg.source {
                Some(source) => Some(SourceId::from_url(source.source_str())?),
                None => get_source_id(pkg),
            };
            let Some(source) = source else { continue };
            let id = PackageId::try_new(pkg.name.as_str(), &pkg.version, source)?;
            // A checksum on the package is encoding 2.
            if let Some(cksum) = &pkg.checksum {
                version = version.max(ResolveVersion::V2);
                checksums.insert(id, Some(cksum.clone()));
            }
            assert!(live_pkgs.insert(enc_id, (id, pkg)).is_none())
        }
        live_pkgs
    };

    // name -> version -> source -> id, to find the ids of edges written briefly.
    let mut map: HashMap<&str, HashMap<String, HashMap<SourceId, PackageId>>> = HashMap::default();
    for (id, _) in live_pkgs.values() {
        map.entry(id.name().as_str())
            .or_default()
            .entry(id.version().to_string())
            .or_default()
            .insert(id.source_id(), *id);
    }

    let mut lookup_id = |enc_id: &TomlLockfilePackageId| -> Option<PackageId> {
        let by_version = map.get(enc_id.name.as_str())?;
        let by_source = match &enc_id.version {
            Some(version) => by_version.get(version)?,
            None => {
                version = version.max(ResolveVersion::V2);
                if by_version.len() == 1 {
                    by_version.values().next().unwrap()
                } else {
                    return None;
                }
            }
        };
        match &enc_id.source {
            Some(source) => by_source.get(&SourceId::from_url(source.source_str()).ok()?).cloned(),
            None => {
                // A path package is never written with a source; otherwise a single
                // package of this name and version is encoding 2. Anything else is a bad merge
                // of the lock file, and is ignored.
                let mut path_packages = by_source.values().filter(|p| p.source_id().is_path());
                if let Some(path) = path_packages.next() {
                    if path_packages.next().is_some() {
                        return None;
                    }
                    Some(*path)
                } else if by_source.len() == 1 {
                    let id = by_source.values().next().unwrap();
                    version = version.max(ResolveVersion::V2);
                    Some(*id)
                } else {
                    None
                }
            }
        }
    };

    let mut g = Graph::new();
    for (id, _) in live_pkgs.values() {
        g.add(*id);
    }
    for &(ref id, pkg) in live_pkgs.values() {
        let Some(ref deps) = pkg.dependencies else { continue };
        for edge in deps.iter() {
            if let Some(to_depend_on) = lookup_id(edge) {
                g.link(*id, to_depend_on);
            }
        }
    }

    let replacements = {
        let mut replacements = HashMap::default();
        for &(ref id, pkg) in live_pkgs.values() {
            if let Some(ref replace) = pkg.replace {
                assert!(pkg.dependencies.is_none());
                if let Some(replace_id) = lookup_id(replace) {
                    replacements.insert(*id, replace_id);
                }
            }
        }
        replacements
    };

    let mut metadata = resolve.metadata.unwrap_or_default();

    // Encoding 1 keeps the checksums in `[metadata]`.
    let prefix = "checksum ";
    let mut to_remove = Vec::new();
    for (k, v) in metadata.iter().filter(|p| p.0.starts_with(prefix)) {
        to_remove.push(k.to_owned());
        let k = k.strip_prefix(prefix).unwrap();
        let enc_id: TomlLockfilePackageId = k
            .parse()
            .with_context(|| "internal error: invalid encoding of checksum in lockfile")?;
        let Some(id) = lookup_id(&enc_id) else { continue };
        let v = if v == "<none>" { None } else { Some(v.to_owned()) };
        checksums.insert(id, v);
    }
    // Checksums in `[metadata]` of an encoding 2 file are a bad merge: drop them all, to be
    // computed again.
    if !to_remove.is_empty() && version >= ResolveVersion::V2 {
        checksums.clear();
    }
    for k in to_remove {
        metadata.remove(&k);
    }

    let mut unused_patches = Vec::new();
    for pkg in resolve.patch.unused {
        let source = match &pkg.source {
            Some(source) => Some(SourceId::from_url(source.source_str())?),
            None => get_source_id(&pkg),
        };
        let Some(src) = source else { continue };
        unused_patches.push(PackageId::try_new(pkg.name.as_str(), &pkg.version, src)?);
    }

    // Encoding 1 sometimes ended in a blank line. A lock file of one package with one
    // newline at its end has nothing else to say it is encoding 2, which it then is.
    if original.ends_with('\n')
        && !original.ends_with("\n\n")
        && version == ResolveVersion::V1
        && g.iter().count() == 1
    {
        version = ResolveVersion::V2;
    }

    Ok(Resolve::new(
        g,
        replacements,
        HashMap::default(),
        checksums,
        metadata,
        unused_patches,
        version,
        HashMap::default(),
    ))
}

/// How many packages of a name and version the resolve has, which decides how briefly an
/// edge can be written.
pub(crate) struct EncodeState<'a> {
    counts: Option<HashMap<InternedString, HashMap<&'a semver::Version, usize>>>,
}

impl<'a> EncodeState<'a> {
    pub(crate) fn new(resolve: &'a Resolve) -> EncodeState<'a> {
        let counts = (resolve.version() >= ResolveVersion::V2).then(|| {
            let mut map: HashMap<_, HashMap<_, usize>> = HashMap::default();
            for id in resolve.iter() {
                *map.entry(id.name()).or_default().entry(id.version()).or_insert(0) += 1;
            }
            map
        });
        EncodeState { counts }
    }
}

struct EncodedPackage {
    name: String,
    version: String,
    source: Option<TomlLockfileSourceId>,
    checksum: Option<String>,
    dependencies: Option<Vec<TomlLockfilePackageId>>,
    replace: Option<TomlLockfilePackageId>,
}

fn encodable_resolve_node(
    id: PackageId,
    resolve: &Resolve,
    state: &EncodeState<'_>,
) -> EncodedPackage {
    let (replace, deps) = match resolve.replacement(id) {
        Some(id) => (Some(encodable_package_id(id, state, resolve.version())), None),
        None => {
            let mut deps = resolve
                .deps_not_replaced(id)
                .map(|(id, _)| encodable_package_id(id, state, resolve.version()))
                .collect::<Vec<_>>();
            deps.sort();
            (None, Some(deps))
        }
    };
    EncodedPackage {
        name: id.name().to_string(),
        version: id.version().to_string(),
        source: encodable_source_id(id.source_id(), resolve.version()),
        dependencies: deps,
        replace,
        checksum: if resolve.version() >= ResolveVersion::V2 {
            resolve.checksums().get(&id).and_then(|s| s.clone())
        } else {
            None
        },
    }
}

pub(crate) fn encodable_package_id(
    id: PackageId,
    state: &EncodeState<'_>,
    resolve_version: ResolveVersion,
) -> TomlLockfilePackageId {
    let mut version = Some(id.version().to_string());
    let mut id_to_encode = id.source_id();
    // Before encoding 3 an edge to `branch = "master"` was written as one to the default
    // branch.
    if resolve_version <= ResolveVersion::V2
        && let Some(GitReference::Branch(b)) = id_to_encode.git_reference()
        && b == "master"
    {
        id_to_encode = SourceId::for_git(id_to_encode.url(), GitReference::DefaultBranch).unwrap();
    }
    let mut source = encodable_source_id(id_to_encode.without_precise(), resolve_version);
    if let Some(counts) = &state.counts {
        let version_counts = &counts[&id.name()];
        if version_counts[&id.version()] == 1 {
            source = None;
            if version_counts.len() == 1 {
                version = None;
            }
        }
    }
    TomlLockfilePackageId { name: id.name().to_string(), version, source }
}

fn encodable_source_id(id: SourceId, version: ResolveVersion) -> Option<TomlLockfileSourceId> {
    if id.is_path() {
        return None;
    }
    let url = if version >= ResolveVersion::V4 {
        id.as_encoded_url().to_string()
    } else {
        id.as_url().to_string()
    };
    Some(TomlLockfileSourceId::new(url).expect("source ID should have valid URLs"))
}

fn toml_str(s: &str) -> toml::Value {
    toml::Value::String(s.to_owned())
}

fn emit_package(dep: &EncodedPackage, out: &mut String) {
    out.push_str(&format!("name = {}\n", toml_str(&dep.name)));
    out.push_str(&format!("version = {}\n", toml_str(&dep.version)));
    if let Some(source) = &dep.source {
        out.push_str(&format!("source = {}\n", toml_str(&source.source_str)));
    }
    if let Some(checksum) = &dep.checksum {
        out.push_str(&format!("checksum = {}\n", toml_str(checksum)));
    }
    if let Some(slice) = &dep.dependencies {
        if !slice.is_empty() {
            out.push_str("dependencies = [\n");
            for child in slice.iter() {
                out.push_str(&format!(" {},\n", toml_str(&child.to_string())));
            }
            out.push_str("]\n");
        }
        out.push('\n');
    } else if let Some(replace) = &dep.replace {
        out.push_str(&format!("replace = {}\n\n", toml_str(&replace.to_string())));
    }
}

/// The text of the lock file of `resolve`, keeping the comments at the top of `orig` (the
/// lock file there was) after cargo's two.
pub fn serialize_resolve(resolve: &Resolve, orig: Option<&str>) -> String {
    let mut ids: Vec<_> = resolve.iter().collect();
    ids.sort();
    let state = EncodeState::new(resolve);
    let packages: Vec<_> =
        ids.iter().map(|&id| encodable_resolve_node(id, resolve, &state)).collect();

    let mut metadata = resolve.metadata().clone();
    if resolve.version() == ResolveVersion::V1 {
        for &id in ids.iter().filter(|id| !id.source_id().is_path()) {
            let checksum = match resolve.checksums()[&id] {
                Some(ref s) => &s[..],
                None => "<none>",
            };
            let id = encodable_package_id(id, &state, resolve.version());
            metadata.insert(format!("checksum {}", id), checksum.to_owned());
        }
    }

    let unused: Vec<_> = resolve
        .unused_patches()
        .iter()
        .map(|id| EncodedPackage {
            name: id.name().to_string(),
            version: id.version().to_string(),
            source: encodable_source_id(id.source_id(), resolve.version()),
            dependencies: None,
            replace: None,
            checksum: if resolve.version() >= ResolveVersion::V2 {
                resolve.checksums().get(id).and_then(|x| x.clone())
            } else {
                None
            },
        })
        .collect();

    let mut out = String::new();
    out.push_str(MARKER_LINE);
    out.push('\n');
    out.push_str(EXTRA_LINE);
    out.push('\n');
    if let Some(orig) = orig {
        let mut comments = orig.lines().take_while(|line| line.starts_with('#'));
        if let Some(first) = comments.next() {
            if first != MARKER_LINE {
                out.push_str(first);
                out.push('\n');
            }
            if let Some(second) = comments.next() {
                if second != EXTRA_LINE {
                    out.push_str(second);
                    out.push('\n');
                }
                for line in comments {
                    out.push_str(line);
                    out.push('\n');
                }
            }
        }
    }

    if let Some(version) = resolve.version().number() {
        out.push_str(&format!("version = {}\n\n", toml::Value::Integer(version.into())));
    }

    for dep in &packages {
        out.push_str("[[package]]\n");
        emit_package(dep, &mut out);
    }

    for entry in &unused {
        out.push_str("[[patch.unused]]\n");
        emit_package(entry, &mut out);
        out.push('\n');
    }

    if !metadata.is_empty() {
        let meta_table: toml::Table =
            metadata.into_iter().map(|(k, v)| (k, toml::Value::String(v))).collect();
        let mut meta_doc = toml::Table::new();
        meta_doc.insert("metadata".to_owned(), toml::Value::Table(meta_table));
        out.push_str(&meta_doc.to_string());
    }

    // Encoding 1 could end in blank lines, and keeps them; the others end in one newline.
    if resolve.version() >= ResolveVersion::V2 {
        while out.ends_with("\n\n") {
            out.pop();
        }
    }
    out
}

/// `--locked` or `--frozen`: the lock file may not change.
#[derive(Clone, Copy)]
pub struct Locked<'a> {
    /// The flag as the user wrote it, `--locked` or `--frozen`.
    pub flag: &'a str,
    /// Where the lock file is, for the error.
    pub path: &'a Path,
    /// The workspace's path packages, to read both lock files back.
    pub path_deps: &'a PathDeps,
}

/// The same lock file: the same lines, or under [`Locked`] the same resolve read back from
/// both, so a lock file differing only in its encoding or its spacing is left alone.
pub fn are_equal_lockfiles(orig: &str, current: &str, locked: Option<Locked<'_>>) -> bool {
    if orig.lines().eq(current.lines()) {
        return true;
    }
    let Some(locked) = locked else { return false };
    let same = || -> Result<bool> {
        let old = into_resolve(parse(orig)?, orig, locked.path_deps)?;
        let new = into_resolve(parse(current)?, current, locked.path_deps)?;
        Ok(old == new)
    };
    matches!(same(), Ok(true))
}

/// What cargo writes to `Cargo.lock` after a resolve: `None` when the lock file there
/// (`orig`) is already the same, and otherwise the text, raised to the encoding a new lock
/// file of the workspace would have (from its lowest `rust-version`) if it was older. A lock
/// file left as it was keeps its encoding. Under [`Locked`] a change is an error.
pub fn lockfile_to_write(
    resolve: &mut Resolve,
    orig: Option<&str>,
    lowest_rust_version: Option<&RustVersion>,
    locked: Option<Locked<'_>>,
) -> Result<Option<String>> {
    let mut out = serialize_resolve(resolve, orig);
    if let Some(orig) = orig
        && are_equal_lockfiles(orig, &out, locked)
    {
        return Ok(None);
    }
    if let Some(locked) = locked {
        let action = if orig.is_some() { "update" } else { "create" };
        let (path, flag) = (locked.path.display(), locked.flag);
        bail!(
            "cannot {action} the lock file {path} because {flag} was passed to prevent this\n\
             help: to generate the lock file without accessing the network, \
             remove the {flag} flag and use --offline instead."
        );
    }
    let default_version = ResolveVersion::with_rust_version(lowest_rust_version);
    if resolve.version() < default_version {
        resolve.set_version(default_version);
        out = serialize_resolve(resolve, orig);
    }
    Ok(Some(out))
}
