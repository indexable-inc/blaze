//! `Cargo.lock` read and written as cargo 1.99.0 does: real lock files of every encoding read
//! and written back byte for byte, and cargo's `tests/testsuite/lockfile_compat.rs` (MIT or
//! Apache-2.0) ported, with the resolve the resolver would hand over built by hand.

use std::path::{Path, PathBuf};

use anyhow::Result;
use blaze_resolve::lockfile::{self, Locked, PathDeps};
use blaze_resolve::{GitReference, PackageId, Resolve, ResolveVersion, RustVersion, SourceId};
use url::Url;

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";
const CKSUM: &str = "8e1b9346248cf3391ead604c4407258d327c28e37209f6d56127598165165dda";
const SHA: &str = "0123456789abcdef0123456789abcdef01234567";

/// A path package's source: an absolute directory, which `/ws` is not on Windows. What a lock
/// file says of one is its name and version, not where it is.
fn path_source(name: &str, version: &str) -> SourceId {
    let root = if cfg!(windows) { "C:/ws" } else { "/ws" };
    SourceId::for_path(&PathBuf::from(format!("{root}/{name}-{version}"))).unwrap()
}

/// Each entry without a source stands for a path package of its own directory.
fn path_deps(toml: &lockfile::TomlLockfile) -> PathDeps {
    let mut deps = PathDeps::default();
    for pkg in toml.package.iter().flatten().chain(&toml.root).chain(&toml.patch.unused) {
        if pkg.source.is_none() {
            deps.entry(pkg.name.clone())
                .or_default()
                .insert(pkg.version.parse().unwrap(), path_source(&pkg.name, &pkg.version));
        }
    }
    deps
}

fn read(text: &str) -> Result<Resolve> {
    let toml = lockfile::parse(text)?;
    let deps = path_deps(&toml);
    lockfile::into_resolve(toml, text, &deps)
}

fn id(name: &str, version: &str, source: SourceId) -> PackageId {
    PackageId::try_new(name, version, source).unwrap()
}

fn crates_io(name: &str, version: &str) -> PackageId {
    id(name, version, SourceId::from_url(CRATES_IO).unwrap())
}

fn path(name: &str, version: &str) -> PackageId {
    id(name, version, path_source(name, version))
}

fn git(name: &str, version: &str, url: &str, reference: GitReference) -> PackageId {
    let source = SourceId::for_git(&Url::parse(url).unwrap(), reference).unwrap();
    id(name, version, source.with_git_precise(Some(SHA.into())))
}

/// What the resolver hands over: the packages with their edges, and checksums.
fn resolve(
    edges: &[(PackageId, &[PackageId])],
    checksums: &[(PackageId, Option<&str>)],
    version: ResolveVersion,
) -> Resolve {
    let mut graph = blaze_resolve::Graph::new();
    for (from, tos) in edges {
        graph.add(*from);
        for to in *tos {
            graph.link(*from, *to);
        }
    }
    let checksums = checksums.iter().map(|(id, c)| (*id, c.map(str::to_owned))).collect();
    let (replacements, features, metadata, summaries) = Default::default();
    Resolve::new(graph, replacements, features, checksums, metadata, vec![], version, summaries)
}

/// `foo 0.0.1` depending on `bar 0.1.0` from crates.io, the project of most of cargo's tests.
fn foo_bar(checksum: Option<&str>, version: ResolveVersion) -> Resolve {
    let (root, bar) = (path("foo", "0.0.1"), crates_io("bar", "0.1.0"));
    resolve(&[(root, &[bar]), (bar, &[])], &[(bar, checksum), (root, None)], version)
}

/// What cargo writes for a resolve whose lock file was `orig`, as `write_pkg_lockfile` does
/// once the resolve took over the lock file's checksums and encoding.
fn write(new: Resolve, orig: Option<&str>, locked: Option<Locked<'_>>) -> Result<Option<String>> {
    write_msrv(new, orig, locked, None)
}

fn write_msrv(
    mut new: Resolve,
    orig: Option<&str>,
    locked: Option<Locked<'_>>,
    msrv: Option<&RustVersion>,
) -> Result<Option<String>> {
    if let Some(orig) = orig {
        new.merge_from(&read(orig)?)?;
    }
    lockfile::lockfile_to_write(&mut new, orig, msrv, locked)
}

