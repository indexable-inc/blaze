/// `rust-version = "1.81"` keeps a new lock file at version 3.
fn msrv_1_81() -> RustVersion {
    "1.81".parse().unwrap()
}

#[test]
fn v3_and_git() {
    let msrv = msrv_1_81();
    let (new, _) = foo_dep1(
        GitReference::Branch("master".into()),
        ResolveVersion::with_rust_version(Some(&msrv)),
    );
    let out = write_msrv(new, Some("version = 3"), None, Some(&msrv)).unwrap();
    assert_eq!(out, Some(foo_dep1_lock(3, &format!("git+file:///ws/dep1?branch=master#{SHA}"))));
}

const SPECIAL_REF: &str = "a-_+#$)";

fn special_refs() -> [(&'static str, GitReference); 3] {
    [
        ("branch", GitReference::Branch(SPECIAL_REF.into())),
        ("tag", GitReference::Tag(SPECIAL_REF.into())),
        ("rev", GitReference::Rev(SPECIAL_REF.into())),
    ]
}

#[test]
fn v3_and_git_url_encoded() {
    for (kind, reference) in special_refs() {
        let msrv = msrv_1_81();
        let (new, _) = foo_dep1(reference, ResolveVersion::with_rust_version(Some(&msrv)));
        let out = write_msrv(new, Some("version = 3"), None, Some(&msrv)).unwrap();
        let source = format!("git+file:///ws/dep1?{kind}={SPECIAL_REF}#{SHA}");
        assert_eq!(out, Some(foo_dep1_lock(3, &source)), "{kind}");
    }
}

#[test]
fn v4_and_git_url_encoded() {
    for (kind, reference) in special_refs() {
        let (new, dep1) = foo_dep1(reference, ResolveVersion::default());
        let out = write(new, Some("version = 4"), None).unwrap().unwrap();
        let source = format!("git+file:///ws/dep1?{kind}=a-_%2B%23%24%29#{SHA}");
        assert_eq!(out, foo_dep1_lock(4, &source), "{kind}");
        // Version 4 reads back the same reference, so the repository is not fetched again.
        let back = read(&out).unwrap();
        let read_dep1 = back.iter().find(|id| id.name() == "dep1").unwrap();
        assert_eq!(
            read_dep1.source_id().git_reference(),
            dep1.source_id().git_reference(),
            "{kind}"
        );
        assert_eq!(read_dep1.source_id().precise_git_fragment(), Some(SHA), "{kind}");
    }
}

