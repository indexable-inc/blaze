fn check_dir(dir: &Path) -> usize {
    let mut checked = 0;
    let mut entries: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).collect();
    entries.sort();
    for path in entries.iter().filter(|p| p.extension().is_some_and(|e| e == "lock")) {
        let text = std::fs::read_to_string(path).unwrap();
        let resolve = read(&text).unwrap_or_else(|e| panic!("{}: {e:#}", path.display()));
        let out = lockfile::serialize_resolve(&resolve, Some(&text));
        if out != text {
            let first = text.lines().zip(out.lines()).position(|(a, b)| a != b);
            panic!(
                "{} ({:?}) is written back differently, first at line {:?}",
                path.display(),
                resolve.version(),
                first.map(|l| l + 1)
            );
        }
        checked += 1;
    }
    checked
}

#[test]
fn real_lock_files_roundtrip() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/lockfiles");
    assert_eq!(check_dir(&dir), 8);
}

/// `BLAZE_RESOLVE_LOCKFILES=dir` checks the lock files of another directory too.
#[test]
fn more_lock_files_roundtrip() {
    if let Some(dir) = std::env::var_os("BLAZE_RESOLVE_LOCKFILES") {
        assert!(check_dir(Path::new(&dir)) > 0);
    }
}

