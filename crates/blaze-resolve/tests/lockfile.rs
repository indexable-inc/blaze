#[test]
fn with_msrv() {
    let v3 = format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "bar"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{CKSUM}"

[[package]]
name = "foo"
version = "0.0.1"
dependencies = [
 "bar",
]
"#
    );
    let v2 = format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
[[package]]
name = "bar"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{CKSUM}"

[[package]]
name = "foo"
version = "0.0.1"
dependencies = [
 "bar",
]
"#
    );
    let v1 = format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
[[package]]
name = "bar"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "foo"
version = "0.0.1"
dependencies = [
 "bar 0.1.0 (registry+https://github.com/rust-lang/crates.io-index)",
]

[metadata]
"checksum bar 0.1.0 (registry+https://github.com/rust-lang/crates.io-index)" = "{CKSUM}"
"#
    );
    #[rustfmt::skip]
    let cases = [
        ("1.37", None, 1), ("1.37", Some(1), 1), ("1.37", Some(2), 2), ("1.37", Some(3), 3), ("1.37", Some(4), 4),
        ("1.38", None, 1),
        ("1.40", None, 1),
        ("1.41", None, 2), ("1.41", Some(1), 1), ("1.41", Some(2), 2), ("1.41", Some(3), 3), ("1.41", Some(4), 4),
        ("1.47", None, 2),
        ("1.48", None, 2),
        ("1.53", None, 3), ("1.53", Some(1), 1), ("1.53", Some(2), 2), ("1.53", Some(3), 3), ("1.53", Some(4), 4),
        ("1.78", None, 3),
        ("1.82", None, 3),
        ("1.83", None, 4), ("1.83", Some(1), 1), ("1.83", Some(2), 2), ("1.83", Some(3), 3), ("1.83", Some(4), 4),
    ];
    for (msrv, existing, expected) in cases {
        let msrv_parsed: RustVersion = msrv.parse().unwrap();
        let orig = existing.map(|v| match v {
            1 => v1.clone(),
            2 => v2.clone(),
            3 => v3.clone(),
            v => format!("version = {v}"),
        });
        let new = foo_bar(Some(CKSUM), ResolveVersion::with_rust_version(Some(&msrv_parsed)));
        let out = write_msrv(new, orig.as_deref(), None, Some(&msrv_parsed)).unwrap();
        let lock = out.or(orig).unwrap();
        let toml: toml::Table = lock.parse().unwrap();
        let actual = match toml.get("version").and_then(|v| v.as_integer()) {
            Some(v) => v,
            None if lock.contains("\nchecksum = ") => 2,
            None => 1,
        };
        assert_eq!(actual, expected, "msrv: {msrv}, existing lock file: {existing:?}");
    }
}
