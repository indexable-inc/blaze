fn foo_dep1(reference: GitReference, version: ResolveVersion) -> (Resolve, PackageId) {
    let (root, dep1) = (path("foo", "0.0.1"), git("dep1", "0.5.0", "file:///ws/dep1", reference));
    (resolve(&[(root, &[dep1]), (dep1, &[])], &[(dep1, None), (root, None)], version), dep1)
}

