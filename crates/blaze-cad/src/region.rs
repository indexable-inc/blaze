/// Maximum Newton projection iterations for [`snap_to_surface`] (rule 18).
const MAX_SNAP_ITERS: u32 = 16;
/// Convergence tolerance for [`snap_to_surface`] (1 nm: the kernel's exact length grid).
const SNAP_CONVERGE_M: f64 = 1e-9;
/// Maximum residual accepted after [`MAX_SNAP_ITERS`] iterations before failing.
const SNAP_MAX_RESIDUAL_M: f64 = 1e-3;
/// Maximum total curve samples produced by [`project_curve_to_surface`] (rule 18).
const MAX_CURVE_SAMPLES: usize = 16_384;
/// Maximum samples per segment accepted by [`project_curve_to_surface`] (rule 18).
const MAX_SAMPLES_PER_SEGMENT: u32 = 256;
/// Maximum pattern elements generated by [`fill_region_pattern`] (rule 18).
const MAX_PATTERN_ELEMENTS: u32 = 512;
/// Samples along each rib line when trimming to `TrimMode::CompleteOnly`.
const COMPLETE_RIB_SCAN_STEPS: u32 = 64;
/// Default projection half-depth for [`PanelOpts`] (`14.0 mm` in nanometres).
/// Deep enough to clear typical panel pockets and curved-surface sag without punching through
/// the opposite wall of a thin housing.
const DEFAULT_PANEL_PROJECTION_NM: i64 = 14_000_000;
/// Default projection half-depth for [`PatternOpts`] (`12.0 mm` in nanometres).
const DEFAULT_PATTERN_PROJECTION_NM: i64 = 12_000_000;

