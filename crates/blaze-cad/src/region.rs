/// An orthonormal frame anchored on a live zero-level CAD surface `f(p) = 0`, together with
/// principal directional curvatures along its local tangent axes.
///
/// The basis `(tangent_u, tangent_v, normal)` is right-handed: `normal × tangent_u = tangent_v`
/// and `tangent_u × tangent_v = normal`.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct AttachmentFrame {
    pub name: Name,
    /// Exact point on the live zero-level surface `f(p) = 0` (metres, part-local).
    pub origin: Vec3,
    /// Exact outward unit normal `∇f / |∇f|`.
    pub normal: Vec3,
    /// Unit tangent along local +U (right).
    pub tangent_u: Vec3,
    /// Unit tangent along local +V (`normal × tangent_u`, up on surface).
    pub tangent_v: Vec3,
    /// Principal directional curvature along `tangent_u` (1/m; positive = convex).
    pub curvature_u: f64,
    /// Principal directional curvature along `tangent_v` (1/m; positive = convex).
    pub curvature_v: f64,
}

impl AttachmentFrame {
    /// Construct a deterministically orthonormalized right-handed [`AttachmentFrame`] at a
    /// surface point `origin` with outward `normal`, aligning local `+V` as closely as possible
    /// with `up_hint`.
    pub fn from_surface_point(
        name: Name,
        origin: Vec3,
        normal: Vec3,
        up_hint: Vec3,
        curvature_u: f64,
        curvature_v: f64,
    ) -> AttachmentFrame {
        let n = normal.normalized().unwrap_or(Vec3::new(0.0, 0.0, 1.0));
        let v_proj = if finite_vec3(up_hint) {
            (up_hint - n * up_hint.dot(n)).normalized()
        } else {
            None
        };
        let v_seed = v_proj.unwrap_or_else(|| {
            let fallback = if n.z.abs() < 0.9 {
                Vec3::new(0.0, 0.0, 1.0)
            } else if n.y.abs() < 0.9 {
                Vec3::new(0.0, 1.0, 0.0)
            } else {
                Vec3::new(1.0, 0.0, 0.0)
            };
            (fallback - n * fallback.dot(n)).normalized().unwrap_or(Vec3::new(0.0, 1.0, 0.0))
        });
        let tangent_u = v_seed.cross(n).normalized().unwrap_or(Vec3::new(1.0, 0.0, 0.0));
        let tangent_v = n.cross(tangent_u).normalized().unwrap_or(v_seed);
        let ku = if curvature_u.is_finite() { curvature_u } else { 0.0 };
        let kv = if curvature_v.is_finite() { curvature_v } else { 0.0 };
        AttachmentFrame {
            name,
            origin,
            normal: n,
            tangent_u,
            tangent_v,
            curvature_u: ku,
            curvature_v: kv,
        }
    }

    /// Rigid [`Placement`] mapping local `(u, v, n)` coordinates onto this surface frame
    /// (`local +X -> tangent_u`, `local +Y -> tangent_v`, `local +Z -> normal`, origin at
    /// `self.origin`).
    pub fn placement(&self) -> Placement {
        let base = Placement::along(self.normal, self.origin).unwrap_or(Placement::IDENTITY);
        let lin = base.linear();
        let x0 = lin.column(0);
        let y0 = lin.column(1);
        let cos_t = self.tangent_u.dot(x0);
        let sin_t = self.tangent_u.dot(y0);
        let theta = blaze_math::atan2(sin_t, cos_t);
        if !theta.is_finite() || theta.abs() <= 1e-12 {
            base
        } else {
            base.then_after(&Placement::rotation(Axis::Z, Angle::radians(theta)))
        }
    }

    /// Project a part-local world point `p` (metres) into frame-local `(u, v, n)` coordinates
    /// relative to `self.origin`.
    #[inline]
    pub fn project_local(&self, p: Vec3) -> Vec3 {
        let d = p - self.origin;
        Vec3::new(d.dot(self.tangent_u), d.dot(self.tangent_v), d.dot(self.normal))
    }

    /// Map frame-local `(u, v, n)` coordinates (metres) back to part-local 3D coordinates.
    #[inline]
    pub fn unproject_world(&self, u: f64, v: f64, n: f64) -> Vec3 {
        self.origin + self.tangent_u * u + self.tangent_v * v + self.normal * n
    }

    /// Rotate a frame-local direction vector `(du, dv, dn)` into part-local world coordinates.
    #[inline]
    pub fn to_world_dir(&self, local_dir: Vec3) -> Vec3 {
        self.tangent_u * local_dir.x + self.tangent_v * local_dir.y + self.normal * local_dir.z
    }
}

/// Parametric selector that locates a stable point on a live CAD surface across shape edits.
#[derive(Clone, Copy, PartialEq, Debug)]
pub enum RegionSelector {
    /// Cast a ray through the bbox-normalized coordinate `origin_frac` (`[0, 1]^3`) along `dir`,
    /// pulled back strictly outside the bounding box along `-dir` so entry from outside is
    /// guaranteed, then refine onto `f(p) = 0`.
    RayHit { origin_frac: [f64; 3], dir: [f64; 3] },
    /// Start at the bbox-normalized coordinate `point_frac` (`[0, 1]^3`) and project onto
    /// `f(p) = 0` via bounded damped Newton steps; if `prefer_normal` is set and the initial
    /// snap lands on an opposing face, cast from the `prefer_normal` side to prefer that face.
    ClosestTo { point_frac: [f64; 3], prefer_normal: Option<[f64; 3]> },
    /// Cast a ray from outside the bounding box along `-dir` through the bbox-normalized point
    /// `at_frac` so it lands on the outermost live face in direction `+dir`.
    Extremal { dir: [f64; 3], at_frac: [f64; 3] },
    /// Locate a surface point near an explicit part-local `point`: snaps directly if already
    /// within 0.1 mm of `f(p) = 0` (or if `search_dir` is zero), otherwise casts along
    /// `search_dir` from `point - search_dir * margin`.
    Absolute { point: [Length; 3], search_dir: [f64; 3] },
}

