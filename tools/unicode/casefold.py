"""Writes crates/blaze-fetch/src/casefold.rs, Unicode's full case folding (statuses C and F of
CaseFolding.txt) as a sorted table, from a CaseFolding.txt the input names.

    uv run tools/unicode/casefold.py '{"case_folding": "CaseFolding.txt", "out": "crates/blaze-fetch/src/casefold.rs"}'
"""

import json
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Input:
    case_folding: str
    out: str


def main() -> None:
    raw = json.loads(sys.argv[1])
    given = Input(**raw)
    text = Path(given.case_folding).read_text(encoding="utf-8")
    version = text.splitlines()[0].lstrip("# ").strip()
    rows: list[tuple[int, str]] = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping, _ = (part.strip() for part in line.split(";"))
        if status not in ("C", "F"):
            continue
        folded = "".join(chr(int(it, 16)) for it in mapping.split())
        rows.append((int(code, 16), folded))
    rows.sort()
    out = [
        f"//! Unicode's full case folding (statuses C and F of {version}), generated by",
        "//! tools/unicode/casefold.py; do not edit. Each row is a character and what it folds to,",
        "//! sorted by the character.",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static FOLD: &[(char, &str)] = &[",
    ]
    for code, folded in rows:
        escaped = "".join(f"\\u{{{ord(it):x}}}" for it in folded)
        out.append(f"    ('\\u{{{code:x}}}', \"{escaped}\"),")
    out.append("];")
    Path(given.out).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
