"""Writes `syntax`'s typed views (`crates/syntax/src/view/generated/{nodes,tokens}.rs`) from the
handle `ast` it mirrors (`crates/syntax/src/ast/generated/{nodes,tokens}.rs`): every node, enum,
`Any*` type, accessor and trait impl, each borrowed and `Copy` over `syntax::view::Node<'t>`.

Input: `{"root": "<workspace>"}`, with `"check": true` to write nothing and exit 1 when the views
on disk differ from what would be written. Refuses (exit 2, naming it) any item of the handle
files it doesn't know how to mirror, so nothing is dropped. Only while both exist: once the
handles are deleted (frontend.md item 16), the views are the generated files.
"""

import re
import sys
from dataclasses import dataclass
from pathlib import Path

from typed_input import parse

SCRIPT = "ast_views.py"
HEADER = "//! Generated by `tools/v2/ast_views.py` from `ast/generated/{name}.rs`, do not edit by hand.\n"


@dataclass(frozen=True)
class Input:
    root: str
    check: bool = False


class Refused(Exception):
    pass


STRUCT = re.compile(r"^pub struct (\w+) \{\n    pub\(crate\) syntax: SyntaxNode,\n\}", re.M)
TOKEN_STRUCT = re.compile(r"^pub struct (\w+) \{\n    pub\(crate\) syntax: SyntaxToken,\n\}", re.M)
ENUM = re.compile(r"^#\[derive\(Debug, Clone, PartialEq, Eq, Hash\)\]\npub enum (\w+) \{\n(.*?)^\}", re.M | re.S)
VARIANT = re.compile(r"^    (\w+)\((\w+)\),$", re.M)
IMPL = re.compile(r"^impl (\w+) \{(\}|\n.*?^\})", re.M | re.S)
FN = re.compile(r"pub fn (\w+)")
METHOD = re.compile(
    r"pub fn (\w+)\(&self\) -> (.+?) \{\s*support::(child|children|token)\(&self\.syntax(?:, (.+?))?\)\s*\}",
    re.S,
)
NEW_ANY = re.compile(r"pub fn new<T: ast::(\w+)>\(node: T\) -> (\w+) \{")
TRAIT_IMPL = re.compile(r"^impl ast::(\w+) for (\w+) \{\}$", re.M)
KIND = re.compile(
    r"^impl AstNode for (\w+) \{\n    #\[inline\]\n    fn kind\(\) -> SyntaxKind\n    where\n"
    r"        Self: Sized,\n    \{\n        (\w+)\n    \}",
    re.M,
)
CAN_CAST = re.compile(
    r"^impl AstNode for (\w+) \{\n    #\[inline\]\n    fn can_cast\(kind: SyntaxKind\) -> bool \{\s*"
    r"matches!\(\s*kind,\s*(.*?)\)\s*\}",
    re.M | re.S,
)
TOKEN_KIND = re.compile(
    r"^impl AstToken for (\w+) \{\n    fn can_cast\(kind: SyntaxKind\) -> bool \{ kind == (\w+) \}", re.M
)
FROM = re.compile(r"^impl From<(\w+)> for (\w+) \{", re.M)
ANY_FROM = re.compile(r"fn from\(node: (\w+)\) -> (Any\w+) \{ (Any\w+) \{ syntax: node\.syntax \} \}")


@dataclass
class Accessor:
    name: str
    shape: str  # child, children, token
    of: str  # the node type, or the token kind expression
    ret: str


@dataclass
class Model:
    structs: list[str]
    kinds: dict[str, str]
    methods: dict[str, list[Accessor]]
    enums: list[tuple[str, list[tuple[str, str]]]]
    anys: dict[str, str]  # Any type -> its trait
    any_kinds: dict[str, list[str]]
    any_from: list[tuple[str, str]]
    traits: list[tuple[str, str]]  # (trait, type)


def accessor(name: str, ret: str, shape: str, arg: str | None) -> Accessor:
    ret = " ".join(ret.split())
    match shape:
        case "token":
            if ret != "Option<SyntaxToken>" or arg is None:
                raise Refused(f"token accessor `{name}` returning `{ret}`")
            return Accessor(name, shape, " ".join(arg.split()), ret)
        case "child":
            m = re.fullmatch(r"Option<(\w+)>", ret)
        case _:
            m = re.fullmatch(r"AstChildren<(\w+)>", ret)
    if m is None or arg is not None:
        raise Refused(f"{shape} accessor `{name}` returning `{ret}`")
    return Accessor(name, shape, m.group(1), ret)


def read_nodes(text: str) -> Model:
    structs = STRUCT.findall(text)
    kinds = dict(KIND.findall(text))
    for name in structs:
        if not name.startswith("Any") and name not in kinds:
            raise Refused(f"node `{name}` has no `AstNode::kind`")
    methods: dict[str, list[Accessor]] = {}
    anys: dict[str, str] = {}
    for m in IMPL.finditer(text):
        owner, body = m.group(1), m.group(2)
        found = [accessor(*m.group(1, 2, 3, 4)) for m in METHOD.finditer(body)]
        new = NEW_ANY.search(body)
        if new:
            if new.group(2) != owner:
                raise Refused(f"`{owner}::new` makes a `{new.group(2)}`")
            anys[owner] = new.group(1)
        if len(FN.findall(body)) != len(found) + (1 if new else 0):
            raise Refused(f"an `impl {owner}` method that is not a `support` accessor")
        methods.setdefault(owner, []).extend(found)
    enums = [(name, VARIANT.findall(body)) for name, body in ENUM.findall(text)]
    for name, body in ENUM.findall(text):
        if len(VARIANT.findall(body)) != len([it for it in body.splitlines() if it.strip()]):
            raise Refused(f"enum `{name}` has a variant that is not `Name(Type)`")
    any_kinds = {}
    for name, body in CAN_CAST.findall(text):
        if name in anys:
            any_kinds[name] = [it.strip() for it in body.split("|")]
    for name in anys:
        if name not in any_kinds:
            raise Refused(f"`{name}` has no `can_cast` list")
    any_from = [(m.group(1), m.group(2)) for m in ANY_FROM.finditer(text)]
    traits = [(trait, ty) for trait, ty in TRAIT_IMPL.findall(text)]
    return Model(structs, kinds, methods, enums, anys, any_kinds, any_from, traits)


def lifetimed(ty: str) -> str:
    return f"{ty}<'t>"


def write_nodes(model: Model) -> str:
    out = [HEADER.format(name="nodes")]
    out.append(
        "\n#![allow(non_snake_case)]\n"
        '#![allow(clippy::needless_pass_by_value, reason = "an `AnyHas*` wrapper takes any node of its trait by value")]\n'
        "use crate::{\n"
        "    SyntaxKind::{self, *},\n"
        "    T,\n"
        "    view::{self, AstChildren, AstNode, Node, Token, support},\n"
        "};\n"
        "use std::fmt;\n"
    )
    nodes = [it for it in model.structs if it not in model.anys]
    enum_names = {name for name, _ in model.enums}
    for name in nodes:
        out.append(f"#[derive(Clone, Copy, PartialEq, Eq, Hash)]\npub struct {name}<'t> {{\n    pub(crate) syntax: Node<'t>,\n}}\n")
        accessors = model.methods.get(name, [])
        if not accessors:
            out.append(f"impl {name}<'_> {{}}\n")
            continue
        out.append(f"impl<'t> {name}<'t> {{\n")
        for it in accessors:
            out.append("    #[inline]\n")
            match it.shape:
                case "token":
                    out.append(
                        f"    pub fn {it.name}(self) -> Option<Token<'t>> {{ support::token(self.syntax, {it.of}) }}\n"
                    )
                case "child":
                    out.append(
                        f"    pub fn {it.name}(self) -> Option<{lifetimed(it.of)}> {{ support::child(self.syntax) }}\n"
                    )
                case _:
                    out.append(
                        f"    pub fn {it.name}(self) -> AstChildren<'t, {lifetimed(it.of)}> {{ support::children(self.syntax) }}\n"
                    )
        out.append("}\n")
    for name, variants in model.enums:
        out.append(f"\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum {name}<'t> {{\n")
        out.extend(f"    {var}({ty}<'t>),\n" for var, ty in variants)
        out.append("}\n")
    for name, trait in model.anys.items():
        out.append(
            f"#[derive(Clone, Copy, PartialEq, Eq, Hash)]\npub struct {name}<'t> {{\n    pub(crate) syntax: Node<'t>,\n}}\n"
            f"impl<'t> {name}<'t> {{\n    #[inline]\n"
            f"    pub fn new<T: view::{trait}<'t>>(node: T) -> {name}<'t> {{ {name} {{ syntax: node.syntax() }} }}\n}}\n"
        )
    for name in nodes:
        kind = model.kinds[name]
        out.append(
            f"impl<'t> AstNode<'t> for {name}<'t> {{\n"
            "    #[inline]\n"
            "    fn kind() -> SyntaxKind\n    where\n        Self: Sized,\n    {\n"
            f"        {kind}\n    }}\n"
            "    #[inline]\n"
            f"    fn can_cast(kind: SyntaxKind) -> bool {{ kind == {kind} }}\n"
            "    #[inline]\n"
            f"    fn cast(syntax: Node<'t>) -> Option<Self> {{\n"
            "        if Self::can_cast(syntax.kind()) { Some(Self { syntax }) } else { None }\n    }\n"
            "    #[inline]\n"
            "    fn syntax(&self) -> Node<'t> { self.syntax }\n}\n"
            f"impl fmt::Debug for {name}<'_> {{\n"
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {\n"
            f"        f.debug_struct(\"{name}\").field(\"syntax\", &self.syntax).finish()\n    }}\n}}\n"
        )
    for name, variants in model.enums:
        for var, ty in variants:
            out.append(
                f"impl<'t> From<{ty}<'t>> for {name}<'t> {{\n    #[inline]\n"
                f"    fn from(node: {ty}<'t>) -> {name}<'t> {{ {name}::{var}(node) }}\n}}\n"
            )
        if any(ty in enum_names for _, ty in variants):
            if name != "Stmt":
                raise Refused(f"enum `{name}` nests an enum; only `Stmt` is written by hand")
            continue
        kinds = [model.kinds[ty] for _, ty in variants]
        out.append(
            f"impl<'t> AstNode<'t> for {name}<'t> {{\n    #[inline]\n"
            f"    fn can_cast(kind: SyntaxKind) -> bool {{ matches!(kind, {' | '.join(kinds)}) }}\n"
            "    #[inline]\n"
            f"    fn cast(syntax: Node<'t>) -> Option<Self> {{\n        let res = match syntax.kind() {{\n"
        )
        out.extend(
            f"            {model.kinds[ty]} => {name}::{var}({ty} {{ syntax }}),\n" for var, ty in variants
        )
        out.append("            _ => return None,\n        };\n        Some(res)\n    }\n")
        out.append("    #[inline]\n    fn syntax(&self) -> Node<'t> {\n        match self {\n")
        out.extend(f"            {name}::{var}(it) => it.syntax,\n" for var, _ in variants)
        out.append("        }\n    }\n}\n")
    for name in model.anys:
        out.append(
            f"impl<'t> AstNode<'t> for {name}<'t> {{\n    #[inline]\n"
            f"    fn can_cast(kind: SyntaxKind) -> bool {{ matches!(kind, {' | '.join(model.any_kinds[name])}) }}\n"
            "    #[inline]\n"
            f"    fn cast(syntax: Node<'t>) -> Option<Self> {{ Self::can_cast(syntax.kind()).then_some({name} {{ syntax }}) }}\n"
            "    #[inline]\n"
            "    fn syntax(&self) -> Node<'t> { self.syntax }\n}\n"
            f"impl fmt::Debug for {name}<'_> {{\n"
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {\n"
            f"        f.debug_struct(\"{name}\").field(\"syntax\", &self.syntax).finish()\n    }}\n}}\n"
        )
    for ty, name in model.any_from:
        out.append(
            f"impl<'t> From<{ty}<'t>> for {name}<'t> {{\n    #[inline]\n"
            f"    fn from(node: {ty}<'t>) -> {name}<'t> {{ {name} {{ syntax: node.syntax }} }}\n}}\n"
        )
    for trait, ty in model.traits:
        out.append(f"impl<'t> view::{trait}<'t> for {ty}<'t> {{}}\n")
    for name in [*nodes, *(name for name, _ in model.enums), *model.anys]:
        out.append(
            f"impl fmt::Display for {name}<'_> {{\n"
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {\n"
            "        fmt::Display::fmt(&self.syntax(), f)\n    }\n}\n"
        )
    for name in [*nodes, *(name for name, _ in model.enums), *model.anys]:
        out.append(f"impl view::Typed for crate::ast::{name} {{\n    type Of<'t> = {name}<'t>;\n}}\n")
    return "".join(out)


def write_check(model: Model) -> str:
    """The test that every view accessor answers as its handle's, node by node."""
    out = [HEADER.format(name="nodes")]
    out.append(
        "//! Every accessor of every typed view against the handle's, on the same node.\n\n"
        "use syntax::{AstNode as _, SyntaxNode, ast, view::{self, AstNode as _}};\n\n"
        "fn range(it: &SyntaxNode) -> (syntax::SyntaxKind, syntax::TextRange) {\n"
        "    (it.kind(), it.text_range())\n}\n\n"
        "fn view_range(it: view::Node<'_>) -> (syntax::SyntaxKind, syntax::TextRange) {\n"
        "    (it.kind(), it.text_range())\n}\n\n"
        "/// Checks `handle` and `node`, the same node of the same tree, as every type they cast to.\n"
        "pub fn check(handle: &SyntaxNode, node: view::Node<'_>) {\n"
        "    assert_eq!(range(handle), view_range(node));\n"
    )
    nodes = [it for it in model.structs if it not in model.anys]
    for name in [*nodes, *(name for name, _ in model.enums), *model.anys]:
        out.append(
            f"    assert_eq!(<ast::{name}>::can_cast(handle.kind()), <view::{name}<'_>>::can_cast(node.kind()));\n"
            f"    if let (Some(h), Some(v)) = (ast::{name}::cast(handle.clone()), view::{name}::cast(node)) {{\n"
            "        assert_eq!(range(h.syntax()), view_range(v.syntax()));\n"
        )
        for it in model.methods.get(name, []):
            match it.shape:
                case "token":
                    out.append(
                        f"        assert_eq!(h.{it.name}().map(|it| (it.kind(), it.text_range())), "
                        f"v.{it.name}().map(|it| (it.kind(), it.text_range())), \"{name}::{it.name}\");\n"
                    )
                case "child":
                    out.append(
                        f"        assert_eq!(h.{it.name}().map(|it| range(it.syntax())), "
                        f"v.{it.name}().map(|it| view_range(it.syntax())), \"{name}::{it.name}\");\n"
                    )
                case _:
                    out.append(
                        f"        assert!(h.{it.name}().map(|it| range(it.syntax())).eq("
                        f"v.{it.name}().map(|it| view_range(it.syntax()))), \"{name}::{it.name}\");\n"
                    )
        out.append("    }\n")
    out.append("}\n")
    return "".join(out)


def write_tokens(text: str) -> str:
    names = TOKEN_STRUCT.findall(text)
    kinds = dict(TOKEN_KIND.findall(text))
    out = [HEADER.format(name="tokens")]
    out.append(
        "\nuse crate::{\n    SyntaxKind::{self, *},\n    view::{AstToken, Token},\n};\nuse std::fmt;\n"
    )
    for name in names:
        if name not in kinds:
            raise Refused(f"token `{name}` has no `AstToken::can_cast`")
        kind = kinds[name]
        out.append(
            f"#[derive(Clone, Copy, PartialEq, Eq, Hash)]\npub struct {name}<'t> {{\n    pub(crate) syntax: Token<'t>,\n}}\n"
            f"impl fmt::Display for {name}<'_> {{\n"
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {\n"
            "        fmt::Display::fmt(&self.syntax, f)\n    }\n}\n"
            f"impl<'t> AstToken<'t> for {name}<'t> {{\n"
            f"    fn can_cast(kind: SyntaxKind) -> bool {{ kind == {kind} }}\n"
            "    fn cast(syntax: Token<'t>) -> Option<Self> {\n"
            "        if Self::can_cast(syntax.kind()) { Some(Self { syntax }) } else { None }\n    }\n"
            "    fn syntax(&self) -> Token<'t> { self.syntax }\n}\n"
            f"impl fmt::Debug for {name}<'_> {{\n"
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {\n"
            f"        f.debug_struct(\"{name}\").field(\"syntax\", &self.syntax).finish()\n    }}\n}}\n"
        )
    if len(names) != len(re.findall(r"^pub struct ", text, re.M)):
        raise Refused("a token type that is not a `syntax: SyntaxToken` struct")
    return "".join(out)


def main() -> None:
    match sys.argv[1:]:
        case [text]:
            cfg = parse(Input, text, SCRIPT)
        case _:
            print(f"usage: {SCRIPT} '{{\"root\": \"<workspace>\"}}'", file=sys.stderr)
            sys.exit(2)
    crate = Path(cfg.root) / "crates" / "syntax"
    handles, views = crate / "src" / "ast" / "generated", crate / "src" / "view" / "generated"
    try:
        model = read_nodes((handles / "nodes.rs").read_text())
        nodes, check = write_nodes(model), write_check(model)
        tokens = write_tokens((handles / "tokens.rs").read_text())
    except Refused as e:
        print(f"{SCRIPT}: refused: {e}", file=sys.stderr)
        sys.exit(2)
    stale = []
    outputs = (
        (views / "nodes.rs", nodes),
        (views / "tokens.rs", tokens),
        (crate / "tests" / "view" / "accessors.rs", check),
    )
    for path, text in outputs:
        if cfg.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    for path in stale:
        print(f"{path}: differs from what {SCRIPT} writes", file=sys.stderr)
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
